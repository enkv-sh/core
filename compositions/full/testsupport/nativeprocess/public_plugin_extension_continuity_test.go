func nativeExtensionDutyRecords(t *testing.T, s *workflowServer, root stateformat.Root) []contract.GeneratedDutyRecord {
	t.Helper()
	var duties []contract.GeneratedDutyRecord
	for _, ref := range root.RequiredSupport {
		key, err := stateformat.Key(s.prefix, ref)
		if err != nil {
			t.Fatal(err)
		}
		page, err := stateformat.InspectRequiredSupportPage(s.object(t, key).body)
		if err != nil {
			t.Fatal(err)
		}
		for _, row := range page.Records {
			if row.Kind == contract.GeneratedDutySupportKind {
				duty, err := contract.InspectGeneratedDutyRecord(row.Body)
				if err != nil || duty.DutyID != row.RecordID {
					t.Fatal("selected example Duty is invalid", err)
				}
				duties = append(duties, duty)
			}
		}
	}
	return duties
}

func nativeExtensionCopyExample(t *testing.T, name string) string {
	t.Helper()
	source := nativeGeneratedSourcePath(nativeRepository(t), "sdk/examples/"+name)
	destination := filepath.Join(nativeGeneratedPrivateDirectory(t), name)
	err := filepath.WalkDir(source, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		relative, err := filepath.Rel(source, path)
		if err != nil {
			return err
		}
		target := filepath.Join(destination, relative)
		if entry.IsDir() {
			return os.MkdirAll(target, 0700)
		}
		if !entry.Type().IsRegular() {
			return fs.ErrInvalid
		}
		body, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(target, body, 0600)
	})
	if err != nil {
		t.Fatal("copy independent example source", err)
	}
	return destination
}

func nativeExtensionRewrite(t *testing.T, path, original, replacement string) {
	t.Helper()
	body, err := os.ReadFile(path)
	if err != nil || bytes.Count(body, []byte(original)) != 1 {
		t.Fatal("modified example source anchor differs", filepath.Base(path), err)
	}
	if err := os.WriteFile(path, bytes.Replace(body, []byte(original), []byte(replacement), 1), 0600); err != nil {
		t.Fatal(err)
	}
}

func nativeExtensionBuildAuthor(t *testing.T, directory string) (artifact.LocalPlugin, artifact.Metadata) {
	t.Helper()
	descriptor, _, err := artifact.ReadDescriptor(t.Context(), filepath.Join(directory, "plugin.json"))
	if err != nil {
		t.Fatal(err)
	}
	root := nativeRepository(t)
	owners := []string{directory, nativeGeneratedSourcePath(root, "sdk/artifact"), nativeGeneratedSourcePath(root, "sdk/"+descriptor.Role), nativeGeneratedSourcePath(root, "protocols/"+descriptor.Role)}
	if descriptor.Role != "manifest-generator" {
		owners = append(owners, nativeGeneratedSourcePath(root, "sdk/examples/testservice"))
	}
	workspace := nativePluginWorkspace(t, owners)
	output := filepath.Join(nativeGeneratedPrivateDirectory(t), "build")
	ctx, cancel := context.WithTimeout(t.Context(), 3*time.Minute)
	defer cancel()
	marker, err := artifactbuild.Run(ctx, artifactbuild.Config{Directory: directory, Descriptor: "plugin.json", Command: ".", Output: output, Workspace: workspace})
	if err != nil {
		t.Fatal("modified independent example build failed", err)
	}
	metadata, err := artifact.VerifyBuild(ctx, output)
	identity, identityErr := metadata.Identity()
	if err != nil || identityErr != nil || identity != marker.Artifact || metadata.Name != descriptor.Name || metadata.Role != descriptor.Role {
		t.Fatal("modified independent example facts differ", err, identityErr)
	}
	return artifact.LocalPlugin{Name: descriptor.Name, Directory: output}, metadata
}

