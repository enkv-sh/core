func newNativeExtensionCase(t *testing.T, cli string, builds []artifact.LocalPlugin) *nativeExtensionCase {
	t.Helper()
	service, err := testservice.New(testservice.Config{Token: nativeExtensionBearer, Namespace: "extension"})
	if err != nil {
		t.Fatal(err)
	}
	server := httptest.NewServer(service)
	t.Cleanup(func() {
		server.Close()
		if err := service.Close(); err != nil {
			t.Error(err)
		}
	})
	s := newWorkflowServer(t, "aws", false)
	s.childLimit, s.requestLimit, s.objectLimit = 24, 24*workflowChildRequestLimit, 1024
	path := filepath.Join(t.TempDir(), "configuration.json")
	if err := os.WriteFile(path, workflowSetup(t, s, false), 0600); err != nil {
		t.Fatal(err)
	}
	f := &nativeExtensionCase{cli: cli, store: s, path: path, plugins: newNativePluginFixture(t, builds...), service: service, server: server}
	workflowResult(t, f.run(t, "init", false, nil, "init", "--source", path, "--source-format", "json", "--json"), "success")
	nativeGeneratedReadJSON(t, path, &f.source)
	return f
}

func (f *nativeExtensionCase) run(t *testing.T, phase string, readOnly bool, credentials []string, args ...string) workflowChild {
	t.Helper()
	environment := f.plugins.Environment(t, f.path)
	for _, name := range []string{"ENKV_EXAMPLE_TOKEN", "ENKV_EXAMPLE_TOKEN_B"} {
		if !slices.ContainsFunc(credentials, func(value string) bool { return strings.HasPrefix(value, name+"=") }) {
			environment = append(environment, name+"=")
		}
	}
	environment = append(environment, credentials...)
	child := workflowRunDeclaredEnvironment(t, f.store, f.cli, phase, observer.Policy{NoKMS: readOnly}, nil, environment, []string{"ENKV_EXAMPLE_TOKEN", "ENKV_EXAMPLE_TOKEN_B"}, args...)
	f.children = append(f.children, child)
	var facts nativeGeneratedOutput
	decoded := json.Unmarshal(child.out, &facts) == nil
	state := workflowSafeState(facts.State)
	switch facts.State {
	case "generated-intent-conflict", "stale-generated-epoch":
		state = facts.State
	case "":
		state = "not-at-root"
	}
	t.Logf("independent extension command phase=%s exit=%d decoded=%t state=%s effects=%d duties=%d hazards=%d service=%+v", phase, child.code, decoded, state, len(facts.Effects), len(facts.Duties), len(facts.Hazards), f.service.Counts())
	if bytes.Contains(child.out, []byte(nativeExtensionBearer)) || bytes.Contains(child.diagnostic, []byte(nativeExtensionBearer)) {
		t.Fatal("example credential reached public process output")
	}
	return child
}

func (f *nativeExtensionCase) finish(t *testing.T, commands int, tokenSubjects ...string) {
	t.Helper()
	// The test service's documented deterministic token grammar supplies these
	// expected private bytes; no provider listing or result is used as authority.
	for _, subject := range tokenSubjects {
		value := append([]byte{0, 255}, []byte("extension/"+subject)...)
		encoded := []byte(base64.StdEncoding.EncodeToString(value))
		for _, child := range f.children {
			if bytes.Contains(child.out, value) || bytes.Contains(child.diagnostic, value) || bytes.Contains(child.out, encoded) || bytes.Contains(child.diagnostic, encoded) {
				clear(value)
				clear(encoded)
				t.Fatal("independent generated value reached public process output")
			}
		}
		clear(value)
		clear(encoded)
	}
	nativeMaterializationJoined(t, f.children, commands)
}

