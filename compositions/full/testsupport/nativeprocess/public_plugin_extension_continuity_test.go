	t.Helper()
	settings := map[string]any{"endpoint": f.server.URL + "/", "namespace": " Extension "}
	if subject != nil {
		settings["subject"] = *subject
	}
	f.source["entries"] = map[string]any{
		"PLAIN": map[string]any{"confidentiality": "plain", "recipients": []string{}, "source": map[string]any{"kind": "supplied", "value": "public #selected"}},
		"TOKEN": map[string]any{"confidentiality": "secret", "recipients": []string{}, "source": map[string]any{"kind": "generated", "plugin": "private-local-token", "settings": settings, "epoch": epoch, "retirement": retirement}},
	}
	f.source["outputs"] = map[string]any{"destinations": map[string]any{}, "routing": map[string]any{}}
