package compositionfull

import (
	"bytes"
	"context"
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/rsa"
	"crypto/x509"
	"os"
	"path/filepath"
	"testing"

	"enkv.sh/compositions/configuration"
	"enkv.sh/core/contract"
)

// This source fixture has a current canonical public basis and no selected
// Store image. Callers inject the resource opener when checking source admission.
func configurationAcceptedWorkPair(t *testing.T, family string, format configuration.Format) configurationReaderSource {
	t.Helper()
	provider := contract.AWS
	location := contract.StoreLocation{Provider: provider, Region: "us-east-1", Bucket: "fixture-bucket", PrefixBeforeHEAD: "accepted-work", ExpectedOwner: "123456789012"}
	signingSelector := "arn:aws:kms:us-east-1:123456789012:key/00000001-1111-1111-1111-111111111111"
	encryptionSelector := "arn:aws:kms:us-east-1:123456789012:key/00000002-1111-1111-1111-111111111111"
	if family == "gcp" {
		provider = contract.GCP
		location = contract.StoreLocation{Provider: provider, Region: "australia-southeast1", Bucket: "fixture-bucket", PrefixBeforeHEAD: "accepted-work"}
		signingSelector = "projects/fixture-project/locations/australia-southeast1/keyRings/fixture/cryptoKeys/signing/cryptoKeyVersions/1"
		encryptionSelector = "projects/fixture-project/locations/australia-southeast1/keyRings/fixture/cryptoKeys/encryption/cryptoKeyVersions/1"
	} else if family != "aws" {
		t.Fatal("unknown accepted-work fixture provider")
	}
	id := func(name string) contract.ID {
		return contract.Hash([]byte("accepted-work source " + family + " " + name))
	}
	domain := id("domain")
	store, err := contract.StoreConfigurationID(contract.StoreConfiguration{Provider: provider, ConstructionProfile: contract.StoreConstructionProfile, DomainID: domain, Region: location.Region, Bucket: location.Bucket, PrefixBeforeHEAD: location.PrefixBeforeHEAD, ExpectedOwner: location.ExpectedOwner})
	if err != nil {
		t.Fatal(err)
	}
	signingKey, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	signingPublic, err := x509.MarshalPKIXPublicKey(&signingKey.PublicKey)
	if err != nil {
		t.Fatal(err)
	}
	encryptionKey, err := rsa.GenerateKey(rand.Reader, 3072)
	if err != nil {
		t.Fatal(err)
	}
	encryptionPublic, err := x509.MarshalPKIXPublicKey(&encryptionKey.PublicKey)
	if err != nil {
		t.Fatal(err)
	}
	signing := contract.PublicSigningBinding{Schema: contract.CanonicalSchema, Role: contract.NormalSigningRole, Provider: provider, SigningProfile: contract.P256SigningProfile, BindingID: id("signing binding"), KeySelector: signingSelector, SPKI: signingPublic, Fingerprint: contract.Hash(signingPublic),
		Binding: contract.BindingSubject{Domain: domain, Coordinate: id("coordinate"), Store: store, Trust: id("trust"), PublicKey: contract.Hash(signingPublic), Interpretation: contract.InterpretationID(), ControlIncarnationID: id("control"), Epoch: 1}}
	encryption := contract.KMSBinding{BindingID: id("encryption binding"), BindingIncarnationID: id("encryption incarnation"), BindingSerial: 1, Provider: provider, WrapProfile: contract.RSAOAEPWrapProfile, ProtectionClass: contract.SoftwareProtection, KeySelector: encryptionSelector, SPKI: encryptionPublic, Fingerprint: contract.Hash(encryptionPublic)}
	descriptor := contract.GenesisDescriptorCore{InitID: id("initialization"), DomainID: domain, DescriptorArtifactID: id("descriptor"), ManifestArtifactID: id("manifest"), Provider: provider, StoreID: store, CoordinateID: id("coordinate"), NonBodyID: id("nonbody"), TrustID: id("trust"),
		InterpretationID: contract.InterpretationID(), TrustInterpretationID: contract.TrustInterpretationID(), CompatibilityID: contract.CompatibilityID(), CryptoSupportID: contract.CryptoSupportID(), AuthorityRecipientID: id("authority"), NormalSigning: signing,
		Recipients: []contract.RecipientRecord{{RecipientID: id("authority"), DisplayName: "Authority", Status: contract.CurrentRecipient, CurrentBinding: &encryption}}}
	basis, err := contract.EncodeGenesisDescriptorCore(descriptor)
	if err != nil {
		t.Fatal(err)
	}
	model := &configuration.Model{FileID: id("source file"), DomainID: domain, Provider: provider, Store: location, DomainName: "accepted", Generated: ".enkv/accepted.generated.json", Resolved: true, Basis: configuration.Basis{Descriptor: basis},
		Authority: configuration.Role{ID: id("authority"), DisplayName: "Authority", SigningSelector: signingSelector, EncryptionSelector: encryptionSelector,
			Signing:    configuration.Key{Selector: signingSelector, PublicKey: signingPublic},
			Encryption: configuration.Key{Selector: encryptionSelector, PublicKey: encryptionPublic, Binding: configuration.Binding{ID: encryption.BindingID, Incarnation: encryption.BindingIncarnationID, Serial: 1, Protection: encryption.ProtectionClass}}}}
	var editable, generated bytes.Buffer
	if err := configuration.EmitEditable(&editable, model, format); err != nil {
		t.Fatal(err)
	}
	if err := configuration.EmitGenerated(&generated, model); err != nil {
		t.Fatal(err)
	}
	directory := t.TempDir()
	generatedPath := filepath.Join(directory, ".enkv", "accepted.generated.json")
	if err := os.Mkdir(filepath.Dir(generatedPath), 0700); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(directory, "accepted.json")
	if format == configuration.YAML {
		path = filepath.Join(directory, "accepted.yaml")
	}
	if err := os.WriteFile(path, editable.Bytes(), 0600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(generatedPath, generated.Bytes(), 0600); err != nil {
		t.Fatal(err)
	}
	pair, err := configuration.Capture(context.Background(), path, format)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := pair.Close(); err != nil {
			t.Error(err)
		}
	})
	return configurationReaderSource{pair: pair, path: path, generated: generatedPath, editableBytes: bytes.Clone(editable.Bytes()), generatedBytes: bytes.Clone(generated.Bytes())}
}
