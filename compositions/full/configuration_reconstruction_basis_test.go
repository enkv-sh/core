// full_only: false
func TestReconstructionCommittedBasisReachesFreshPairAdmission(t *testing.T) {
	for _, family := range []string{"aws", "gcp"} {
		t.Run(family, func(t *testing.T) {
			t.Setenv("GOOGLE_API_USE_CLIENT_CERTIFICATE", "false")
			t.Setenv("EXPERIMENTAL_GOOGLE_API_USE_S2A", "false")
			projection, _, source := configurationReconstructionProjection(t, family)
			parts, err := source.archive.SelectedParts()
			if err != nil {
				t.Fatal(err)
			}
			// Expected witness bytes come from the fixed signed archive, never
			// from CopyPublicBasis or the configuration translation being checked.
			var want core.PublicBasis
			for _, part := range parts {
				switch part.Kind {
				case "configuration":
					want.StoreConfiguration = part.Body
				case "HEAD":
					want.HEAD = part.Body
				case "root":
					want.Root = part.Body
					root, err := format.DecodeRoot(part.Body)
					if err != nil {
						t.Fatal(err)
					}
					anchor := root.CurrentAccess.Core.NormalSigning
					if anchor.Provider != source.archive.Family || anchor.Role != contract.NormalSigningRole || anchor.KeySelector != source.archive.SignerSelector || !bytes.Equal(anchor.SPKI, source.archive.SignerPublicKey) {
						t.Fatal("archive selection differs from independent signing resource")
					}
					want.SigningAnchor, err = contract.EncodePublicSigningBinding(anchor)
					if err != nil {
						t.Fatal(err)
					}
				case "recipient page":
					want.RecipientPages = append(want.RecipientPages, part.Body)
				}
			}
			basis, err := projection.CopyPublicBasis(context.Background())
			if err != nil || !sameReconstructedBasis(basis, want) {
				t.Fatal("committed basis differs from complete independent witness", err)
			}
			model, err := ReconstructionConfiguration(context.Background(), projection, basis, ReconstructionConfigurationOptions{Name: "restored", FileID: contract.Hash([]byte("committed reconstruction local identity"))})
			if err != nil {
				t.Fatal("committed reconstruction did not reach existing normalizer", err)
			}
			assertReconstructedSharedRouting(t, model.Public)
			got, _, err := configurationPublicBasis(model)
			if err != nil || !sameReconstructedBasis(got, want) {
				t.Fatal("normalizer did not retain complete committed public basis", err)
			}
			projection.Close()
			for _, body := range append([][]byte{basis.SigningAnchor, basis.StoreConfiguration, basis.HEAD, basis.Root}, basis.RecipientPages...) {
				clear(body)
			}
			got, _, err = configurationPublicBasis(model)
			if err != nil || !sameReconstructedBasis(got, want) {
				t.Fatal("normalized model borrowed reconstruction or caller evidence", err)
			}
			for _, encoding := range []configuration.Format{configuration.JSON, configuration.YAML} {
				var editable, generated bytes.Buffer
				if err := configuration.EmitEditable(&editable, model, encoding); err != nil {
					t.Fatal(err)
				}
				if err := configuration.EmitGenerated(&generated, model); err != nil {
					t.Fatal(err)
				}
				dir := t.TempDir()
				if err := os.Mkdir(filepath.Join(dir, ".enkv"), 0700); err != nil {
					t.Fatal(err)
				}
				if err := os.WriteFile(filepath.Join(dir, model.Generated), generated.Bytes(), 0600); err != nil {
					t.Fatal(err)
				}
				path := filepath.Join(dir, "new-local-filename")
				if err := os.WriteFile(path, editable.Bytes(), 0600); err != nil {
					t.Fatal(err)
				}
				pair, err := configuration.Capture(context.Background(), path, encoding)
				if err != nil {
					t.Fatal(err)
				}
				t.Cleanup(func() {
					if err := pair.Close(); err != nil {
						t.Error(err)
					}
				})
				again, err := configuration.Parse(context.Background(), pair)
				if err != nil {
					t.Fatal(err)
				}
				assertReconstructedSharedRouting(t, again.Public)
				got, _, err := configurationPublicBasis(again)
				if err != nil || !sameReconstructedBasis(got, want) {
					t.Fatal("portable pair changed complete public basis", err)
				}
				// The source omits derived output targets and has source-local
				// recipient order. Compare the complete installed meaning, as the
				// normalizer does before publishing its model.
				validated := validateInstalledConfiguration(context.Background(), again.Public)
				if !validated.Valid || !validated.Complete || !validated.DiagnosticsComplete || !reflect.DeepEqual(validated.Configuration, model.Public) {
					for _, field := range []struct {
						name      string
						got, want any
					}{
						{"store", validated.Configuration.Store, model.Public.Store}, {"authority", validated.Configuration.Authority, model.Public.Authority},
						{"recovery", validated.Configuration.Recovery, model.Public.Recovery}, {"recipients", validated.Configuration.Recipients, model.Public.Recipients},
						{"entries", validated.Configuration.Entries, model.Public.Entries}, {"outputs", validated.Configuration.OutputBindings, model.Public.OutputBindings},
						{"groups", validated.Configuration.Groups, model.Public.Groups}, {"routing", validated.Configuration.Routing, model.Public.Routing},
					} {
						if !reflect.DeepEqual(field.got, field.want) {
							t.Error("complete normalized public field differs:", field.name)
						}
					}
					t.Fatal("portable pair changed complete normalized desired meaning")
				}
				h := &readerHTTPFixture{archive: source.archive, reads: map[string]int{}}
				calls := 0
				installedOpen := configurationReaderOpener(t, configurationReaderSource{archive: source.archive}, h, &calls)
				var offered core.PublicBasis
				open := func(ctx context.Context, c ReaderConfig) (*core.ReaderEngine, error) {
					if c.AWS != nil {
						offered = c.AWS.PublicBasis
					} else {
						offered = c.GCP.PublicBasis
					}
					return installedOpen(ctx, c)
				}
				ctx, cancel := context.WithTimeout(t.Context(), time.Minute)
				candidate := configurationReaderPairWithOutputs(t, family, encoding, nil)
				compared := compareReaderFixture(ctx, contract.Hash([]byte("committed pair fresh admission")), pair, candidate.pair, open)
				cancel()
				if compared.Verdict != contract.ComparisonMatch || compared.StateResult != contract.ReaderSuccess || len(compared.Diagnostics) != 0 || calls != 1 || compared.Observation == nil {
					t.Fatal("portable pair did not admit through fresh ordinary Reader", compared.Verdict, compared.StateResult, compared.Diagnostics)
				}
				for _, body := range append([][]byte{offered.SigningAnchor, offered.StoreConfiguration, offered.HEAD, offered.Root}, offered.RecipientPages...) {
					if !bytes.Equal(body, make([]byte, len(body))) {
						t.Fatal("Reader retained source witness after independent installation")
					}
				}
				h.assertNoEffects(t)
			}
		})
	}
}

func sameReconstructedBasis(got, want core.PublicBasis) bool {
	if len(got.Descriptor) != 0 || len(got.Control) != 0 || len(got.Selection) != 0 || len(got.Enrollment) != 0 || len(got.RecipientPages) != len(want.RecipientPages) {
		return false
	}
	if !bytes.Equal(got.SigningAnchor, want.SigningAnchor) || !bytes.Equal(got.StoreConfiguration, want.StoreConfiguration) || !bytes.Equal(got.HEAD, want.HEAD) || !bytes.Equal(got.Root, want.Root) {
		return false
	}
	for i := range want.RecipientPages {
		if !bytes.Equal(got.RecipientPages[i], want.RecipientPages[i]) {
			return false
		}
	}
	return true
}

