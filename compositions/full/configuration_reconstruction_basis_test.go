func TestReconstructionOwnedBasisTransfersOnceAndClearsOnFailure(t *testing.T) {
	projection, _, _ := configurationReconstructionProjection(t, "aws")
	options := ReconstructionConfigurationOptions{Name: "restored", FileID: contract.Hash([]byte("owned reconstruction local identity"))}
	basis, err := projection.CopyPublicBasis(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	model, err := reconstructionConfigurationOwned(context.Background(), projection, basis, options)
	if err != nil {
		t.Fatal(err)
	}
	got, _, err := configurationPublicBasis(model)
	if err != nil || &got.SigningAnchor[0] != &basis.SigningAnchor[0] || &got.StoreConfiguration[0] != &basis.StoreConfiguration[0] || &got.HEAD[0] != &basis.HEAD[0] || &got.Root[0] != &basis.Root[0] || len(got.RecipientPages) != len(basis.RecipientPages) {
		t.Fatal("owned normalizer copied or lost witness owner", err)
	}
	for i := range got.RecipientPages {
		if &got.RecipientPages[i][0] != &basis.RecipientPages[i][0] {
			t.Fatal("owned normalizer copied recipient page owner")
		}
	}
	otherBasis, err := projection.CopyPublicBasis(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	other, err := reconstructionConfigurationOwned(context.Background(), projection, otherBasis,
		ReconstructionConfigurationOptions{Name: "other", FileID: contract.Hash([]byte("different local file identity"))})
	if err != nil || other.FileID == model.FileID || other.DomainName != "other" || other.Generated != ".enkv/other.generated.json" || !reflect.DeepEqual(other.Public, model.Public) || !reflect.DeepEqual(other.Entries, model.Entries) || !reflect.DeepEqual(other.Basis, model.Basis) {
		t.Fatal("local name or FileID changed authenticated facts", err)
	}
	failed, err := projection.CopyPublicBasis(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	if rejected, err := reconstructionConfigurationOwned(context.Background(), projection, failed, ReconstructionConfigurationOptions{Name: "../invalid", FileID: options.FileID}); err == nil || rejected != nil {
		t.Fatal("invalid local name released a partial model")
	}
	for _, body := range append([][]byte{failed.SigningAnchor, failed.StoreConfiguration, failed.HEAD, failed.Root}, failed.RecipientPages...) {
		if !bytes.Equal(body, make([]byte, len(body))) {
			t.Fatal("failed owned normalization retained provisional witness bytes")
		}
	}
	got, _, err = configurationPublicBasis(model)
	if err != nil || !sameReconstructedBasis(got, basis) {
		t.Fatal("failure cleared another successful model owner", err)
	}
}

