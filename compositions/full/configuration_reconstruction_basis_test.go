func TestInitializationBasisRejectsObservationFields(t *testing.T) {
	_, model, descriptor, manifest := initializationObservationSource(t, configuration.JSON, nil)
	if !validInitializationObservationBasis(model, descriptor, manifest) {
		t.Fatal("genesis fixture did not reach the observation-field gate")
	}
	for name, change := range map[string]func(*configuration.Basis){
		"anchor":              func(b *configuration.Basis) { b.SigningAnchor = []byte{1} },
		"store configuration": func(b *configuration.Basis) { b.StoreConfiguration = []byte{1} },
		"HEAD":                func(b *configuration.Basis) { b.HEAD = []byte{1} },
		"root":                func(b *configuration.Basis) { b.Root = []byte{1} },
		"recipient pages":     func(b *configuration.Basis) { b.RecipientPages = [][]byte{{1}} },
	} {
		t.Run(name, func(t *testing.T) {
			mixed := *model
			change(&mixed.Basis)
			if validInitializationObservationBasis(&mixed, descriptor, manifest) {
				t.Fatal("initialization accepted observation evidence as genesis")
			}
		})
	}
}
