// full_only: false
func TestSuppliedInsertionPreservesDeepFlowSettings(t *testing.T) {
	for _, canonical := range []bool{false, true} {
		t.Run(map[bool]string{false: "author", true: "canonical"}[canonical], func(t *testing.T) {
			exact := strings.Repeat("[", 32) + `{"text":"\u0078","number":1.00}` + strings.Repeat("]", 32)
			view := strings.Replace(exact, "[", "[ # settings comment\n", 1)
			arm := "settings: " + view
			generated := sourceGeneratedJSON
			var intent []byte
			if canonical {
				arm = "canonical: {settings: " + view + "}"
				intent = sourceCanonicalIntent(t, false)[:67]
				intent = binary.BigEndian.AppendUint32(intent, uint32(len(exact)))
				intent = append(intent, exact...)
				generated = sourceGeneratedCanonical(t, map[string][]byte{"old": intent}, nil)
			}
			original := "entries: {old: {confidentiality: secret, recipients: [], source: {kind: generated, plugin: private-token, epoch: 0, " + arm + "}}}"
			editable := strings.Replace(sourceSetupYAML, "entries: {}", original, 1)
			pair := writePair(t, editable, generated, YAML)
			model, err := ParseForSet(t.Context(), pair, "new")
			if err != nil {
				t.Fatal(err)
			}
			before := append([]byte(nil), model.Entries[0].Generated.Settings...)
			edit, err := PrepareSuppliedEdit(pair, model, "new", false, contract.InputEncodingRaw)
			if err != nil {
				t.Fatal(err)
			}
			var out bytes.Buffer
			if err := edit.EmitEditable(t.Context(), &out, model.Generated, []byte("new")); err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(out.String(), view) || strings.Count(out.String(), "# settings comment") != 1 {
				t.Fatal("unchanged settings span or comment changed")
			}
			again, err := Parse(t.Context(), captureEditableEmission(t, out.Bytes(), []byte(generated), YAML, model.Generated))
			if err != nil {
				t.Fatal(err)
			}
			g := again.Entries[1].Generated
			if g == nil || canonical && !bytes.Equal(g.Intent, intent) || !canonical && !bytes.Equal(g.Settings, before) {
				t.Fatal("unselected generator settings changed")
			}
		})
	}
}

// full_only: false
func TestSuppliedConversionRemovesOnlySelectedCanonicalBacking(t *testing.T) {
	for _, format := range []Format{JSON, YAML} {
		for _, confidential := range []bool{false, true} {
			t.Run(map[Format]string{JSON: "json", YAML: "yaml"}[format]+"/"+map[bool]string{false: "plain", true: "secret"}[confidential], func(t *testing.T) {
				intent := sourceCanonicalIntent(t, false)
				row := `{"confidentiality":"secret","recipients":[],"source":{"kind":"generated","plugin":null,"epoch":0,"canonical":{"settings":{}}}}`
				editable := strings.Replace(sourceSetupJSON, `"entries":{}`, `"entries":{"old":`+row+`,"keep":`+row+`}`, 1)
				generated := sourceGeneratedCanonical(t, map[string][]byte{"old": intent, "keep": intent}, nil)
				model, err := Parse(t.Context(), writePair(t, editable, generated, JSON))
				if err != nil {
					t.Fatal(err)
				}
				var source bytes.Buffer
				if err := EmitEditable(&source, model, format); err != nil {
					t.Fatal(err)
				}
				pair := captureEditableEmission(t, source.Bytes(), []byte(generated), format, model.Generated)
				model, err = ParseForSet(t.Context(), pair, "old")
				if err != nil {
					t.Fatal(err)
				}
				edit, err := PrepareSuppliedEdit(pair, model, "old", confidential, contract.InputEncodingRaw)
				if err != nil {
					t.Fatal(err)
				}
				var gotSource, gotGenerated bytes.Buffer
				if err := edit.EmitEditable(t.Context(), &gotSource, model.Generated, []byte("replacement")); err != nil {
					t.Fatal(err)
				}
				var envelope []byte
				if confidential {
					envelope = sourceEditEnvelope(t, "old")
				}
				if err := edit.EmitGenerated(t.Context(), &gotGenerated, envelope); err != nil {
					t.Fatal(err)
				}
				keep := `"keep":"` + base64.StdEncoding.EncodeToString(intent) + `"`
				if !strings.Contains(gotGenerated.String(), keep) || strings.Contains(gotGenerated.String(), `"old":"`+base64.StdEncoding.EncodeToString(intent)+`"`) {
					t.Fatal("selected backing retained or unrelated exact row changed")
				}
				again, err := Parse(t.Context(), captureEditableEmission(t, gotSource.Bytes(), gotGenerated.Bytes(), format, model.Generated))
				if err != nil {
					t.Fatal(err)
				}
				if len(again.Entries) != 2 || again.Entries[0].Name != "keep" || !bytes.Equal(again.Entries[0].Generated.Intent, intent) || again.Entries[1].Generated != nil || again.Entries[1].Secret != confidential {
					t.Fatal("conversion changed unrelated source or selected kind")
				}
			})
		}
	}
}

// full_only: false
func TestCanonicalGeneratorBackingRemovalPreservesOtherCompanionBytes(t *testing.T) {
	for _, tc := range []struct {
		name, rows, want string
		names            []string
	}{
		{"only", `{"old":"@"}`, `{}`, []string{"old"}},
		{"first", `{"old":"@",
 "z":"@"}`, `{"z":"@"}`, []string{"old", "z"}},
		{"middle", `{"a":"@",
 "old":"@" ,	"z":"@"}`, `{"a":"@",
 "z":"@"}`, []string{"a", "old", "z"}},
		{"last", `{"a":"@",
 "old":"@" }`, `{"a":"@" }`, []string{"a", "old"}},
		{"unused-first", `{"a":"@", "old":"@"}`, `{"a":"@"}`, []string{"old"}},
		{"unused-last", `{"old":"@", "z":"@"}`, `{"z":"@"}`, []string{"old"}},
		{"unused-neighbors", `{"a":"@", "old":"@", "z":"@"}`, `{"a":"@", "z":"@"}`, []string{"old"}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			intent := sourceCanonicalIntent(t, false)
			blob := base64.StdEncoding.EncodeToString(intent)
			rows := strings.ReplaceAll(tc.rows, "@", blob)
			wantRows := strings.ReplaceAll(tc.want, "@", blob)
			row := `:{"confidentiality":"secret","recipients":[],"source":{"kind":"generated","plugin":null,"epoch":0,"canonical":{"settings":{}}}}`
			entries := make([]string, 0, len(tc.names))
			for _, name := range tc.names {
				entries = append(entries, `"`+name+`"`+row)
			}
			editable := strings.Replace(sourceSetupJSON, `"entries":{}`, `"entries":{`+strings.Join(entries, ",")+`}`, 1)
			prefix := strings.TrimSuffix(sourceGeneratedJSON, "}") + `,"canonical_records":{"generators":`
			generated := prefix + rows + `,"outputs":{}}}`
			pair := writePair(t, editable, generated, JSON)
			m, err := ParseForSet(t.Context(), pair, "old")
			if err != nil {
				t.Fatal(err)
			}
			edit, err := PrepareSuppliedEdit(pair, m, "old", false, contract.InputEncodingRaw)
			if err != nil {
				t.Fatal(err)
			}
			var out bytes.Buffer
			if err := edit.EmitGenerated(t.Context(), &out, nil); err != nil {
				t.Fatal(err)
			}
			if out.String() != prefix+wantRows+`,"outputs":{}}}` {
				t.Fatal("bytes outside selected row/comma span changed")
			}
		})
	}
}
