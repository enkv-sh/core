func TestCanonicalSourceCutRejectsPreviousEnvelopesAndOpaqueArms(t *testing.T) {
	for _, source := range []string{
		`{"kind":"generated","plugin":null,"epoch":0,"canonical":{"intent_base64":"AAE="}}`,
		`{"kind":"generated","plugin":null,"epoch":0,"canonical":{"settings":{},"intent_base64":"AAE="}}`,
	} {
		p := newParser(t.Context(), strings.NewReader(`{"token":{"confidentiality":"secret","recipients":[],"source":`+source+`}}`), JSON)
		parseEntries(p, &Model{})
		if p.done() == nil {
			t.Fatal("superseded source arm accepted")
		}
	}
	for _, source := range []string{`{"destinations":{"d":{"plugin":null,"canonical":{"binding_base64":"AAE="}}},"routing":{}}`, `{"destinations":{"d":{"plugin":null,"canonical":{"settings":{},"binding_base64":"AAE="}}},"routing":{}}`} {
		p := newParser(t.Context(), strings.NewReader(source), JSON)
		parseOutputs(p, &Model{})
		if p.done() == nil {
			t.Fatal("superseded output arm accepted")
		}
	}
	for _, test := range []struct {
		name, source string
		generated    bool
	}{{"editable", strings.Replace(sourceSetupJSON, "enkv/configuration/v3", "enkv/configuration/v2", 1), false}, {"generated", `{"schema":"enkv/generated/v1"}`, true}} {
		t.Run(test.name, func(t *testing.T) {
			var err error
			if test.generated {
				p := newParser(t.Context(), strings.NewReader(test.source), JSON)
				p.generatedImage = true
				parseGenerated(p, &Model{})
				err = p.done()
			} else {
				path := filepath.Join(t.TempDir(), "configuration.json")
				if err := os.WriteFile(path, []byte(test.source), 0600); err != nil {
					t.Fatal(err)
				}
				pair, captureErr := Capture(t.Context(), path, JSON)
				err = captureErr
				if pair != nil {
					if closeErr := pair.Close(); closeErr != nil {
						t.Error(closeErr)
					}
				}
			}
			var diagnostic *Diagnostic
			if !errors.As(err, &diagnostic) || diagnostic.Reason != "unsupported-schema" || diagnostic.Field != "schema" {
				t.Fatal("previous source envelope did not refuse at schema", err)
			}
		})
	}
}
