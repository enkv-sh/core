// full_only: false
func TestRecoveredCanonicalSettingsHaveNestedViewAndExactCompanion(t *testing.T) {
	for _, format := range []Format{JSON, YAML} {
		t.Run(map[Format]string{JSON: "json", YAML: "yaml"}[format], func(t *testing.T) {
			model, err := Parse(t.Context(), writePair(t, sourceSetupJSON, sourceGeneratedJSON, JSON))
			if err != nil {
				t.Fatal(err)
			}
			exact := []byte(` { "z": [1.00,"\u0078",null], "a": {} } `)
			intent := sourceCanonicalIntent(t, false)[:67]
			intent = binary.BigEndian.AppendUint32(intent, uint32(len(exact)))
			intent = append(intent, exact...)
			model.Entries = []Entry{{Name: "token", Secret: true, Generated: &Generator{Intent: intent, Epoch: 7}}}
			model.Outputs = []OutputBinding{{DestinationID: "private", Binding: contract.NormalOutputBinding{DestinationID: "private", Destination: contract.OutputDestination{ConfigContractID: "private-config", ServiceContractID: "private-service", CanonicalSettings: exact}, Targets: []contract.NormalOutputTarget{}}}}
			outputRecord, err := contract.EncodeNormalOutputBinding(model.Outputs[0].Binding)
			if err != nil {
				t.Fatal(err)
			}
			var editable, generated bytes.Buffer
			if err := EmitEditable(&editable, model, format); err != nil {
				t.Fatal(err)
			}
			if err := EmitGenerated(&generated, model); err != nil {
				t.Fatal(err)
			}
			for _, body := range [][]byte{intent, outputRecord} {
				carrier := []byte(base64.StdEncoding.EncodeToString(body))
				if bytes.Contains(editable.Bytes(), carrier) {
					t.Fatal("editable source contains opaque full record")
				}
				if !bytes.Contains(generated.Bytes(), carrier) {
					t.Fatal("companion does not retain complete exact record")
				}
			}
			if !bytes.Contains(editable.Bytes(), []byte("settings")) || !bytes.Contains(generated.Bytes(), []byte("canonical_records")) {
				t.Fatal("canonical view/backing missing")
			}
			again, err := Parse(t.Context(), captureEditableEmission(t, editable.Bytes(), generated.Bytes(), format, model.Generated))
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(again.Entries[0].Generated.Intent, intent) {
				t.Fatal("exact generator record changed")
			}
			got, err := contract.EncodeNormalOutputBinding(again.Outputs[0].Binding)
			if err != nil || !bytes.Equal(got, outputRecord) {
				t.Fatal("exact output record changed", err)
			}
		})
	}
}

// full_only: false
func TestCanonicalSettingsBackingRequiredAndSourceArmsExclusive(t *testing.T) {
	for _, canonical := range []string{`{"settings":{"x":1}}`, `{"settings":null}`} {
		entries := `"entries":{"token":{"confidentiality":"secret","recipients":[],"source":{"kind":"generated","plugin":"private-token","epoch":7,"canonical":` + canonical + `}}}`
		editable := strings.Replace(sourceSetupJSON, `"entries":{}`, entries, 1)
		if _, err := Parse(t.Context(), writePair(t, editable, sourceGeneratedJSON, JSON)); err == nil {
			t.Fatal("canonical source without saved record accepted")
		}
		source := strings.TrimPrefix(entries, `"entries":`)
		source = strings.Replace(source, `"canonical":`, `"settings":{},"canonical":`, 1)
		p := newParser(t.Context(), strings.NewReader(source), JSON)
		parseEntries(p, &Model{})
		if err := p.done(); err == nil {
			t.Fatal("competing author and recovered settings accepted")
		}
	}
}

