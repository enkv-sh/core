func TestRecoveredCanonicalSettingsEditsPreserveUnchangedTokens(t *testing.T) {
	for _, format := range []Format{JSON, YAML} {
		t.Run(map[Format]string{JSON: "json", YAML: "yaml"}[format], func(t *testing.T) {
			model, err := Parse(t.Context(), writePair(t, sourceSetupJSON, sourceGeneratedJSON, JSON))
			if err != nil {
				t.Fatal(err)
			}
			exact := []byte(` {"number":1.00,"text":"\u0078","change":"before","nested":{"old":true}} `)
			intent := sourceCanonicalIntent(t, false)[:67]
			intent = binary.BigEndian.AppendUint32(intent, uint32(len(exact)))
			intent = append(intent, exact...)
			model.Entries = []Entry{{Name: "token", Secret: true, Generated: &Generator{Intent: intent, Epoch: 7}}}
			model.Outputs = []OutputBinding{{DestinationID: "private", Binding: contract.NormalOutputBinding{DestinationID: "private", Destination: contract.OutputDestination{ConfigContractID: "private-config", ServiceContractID: "private-service", CanonicalSettings: exact}, Targets: []contract.NormalOutputTarget{}}}}
			var editable, generated bytes.Buffer
			if err := EmitEditable(&editable, model, format); err != nil {
				t.Fatal(err)
			}
			if err := EmitGenerated(&generated, model); err != nil {
				t.Fatal(err)
			}
			for _, tc := range []struct {
				name string
				edit func(string) string
				want string
			}{
				{"formatting", func(s string) string {
					if format == YAML {
						return strings.ReplaceAll(s, "text: x", `text: "\u0078"`)
					}
					if strings.Contains(s, `"\u0078"`) {
						return strings.ReplaceAll(s, `"\u0078"`, `"x"`)
					}
					return strings.ReplaceAll(s, `"x"`, `"\u0078"`)
				}, string(exact)},
				{"changed_leaf", func(s string) string {
					if format == YAML {
						return strings.ReplaceAll(s, "change: before", "change: after")
					}
					return strings.ReplaceAll(s, `"before"`, `"after"`)
				}, ` {"number":1.00,"text":"\u0078","change":"after","nested":{"old":true}} `},
			} {
				t.Run(tc.name, func(t *testing.T) {
					source := tc.edit(editable.String())
					if source == editable.String() {
						t.Fatal("edit fixture did not change source")
					}
					again, err := Parse(t.Context(), captureEditableEmission(t, []byte(source), generated.Bytes(), format, model.Generated))
					if err != nil {
						t.Fatal(err)
					}
					got, err := contract.InspectGeneratorIntent(again.Entries[0].Generated.Intent)
					if err != nil || string(got.Settings) != tc.want {
						t.Fatalf("generator candidate=%q want=%q: %v", got.Settings, tc.want, err)
					}
					if string(again.Outputs[0].Binding.Destination.CanonicalSettings) != tc.want {
						t.Fatalf("output candidate=%q want=%q", again.Outputs[0].Binding.Destination.CanonicalSettings, tc.want)
					}
				})
			}
		})
	}
}

