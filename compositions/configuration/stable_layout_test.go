func TestStableGeneratedRecordAlternatives(t *testing.T) {
	pair := writePair(t, sourceSetupJSON, sourceGeneratedJSON, JSON)
	m, err := Parse(context.Background(), pair)
	if err != nil {
		t.Fatal(err)
	}
	m.RecoveryEnabled, m.Recovery = true, m.Authority
	m.Recipients = []Recipient{
		{Reference: "z", ID: m.FileID, Selector: sourceEncryptionSelector, Encryption: m.Authority.Encryption},
		{Reference: "a", ID: m.DomainID, Selector: sourceEncryptionSelector, Encryption: m.Authority.Encryption, Creation: &Creation{Snapshot: m.FileID, Nonce: m.DomainID}},
	}
	envelope := sourceEditEnvelope(t, "z")
	m.Entries = []Entry{
		{Name: "z", Secret: true, Sealed: envelope},
		{Name: "a", Secret: true, Retained: &Pin{Incarnation: m.FileID, Material: m.DomainID}},
	}
	var out bytes.Buffer
	if err := EmitGenerated(&out, m); err != nil {
		t.Fatal(err)
	}
	fragments := []string{
		"\"recipients\": {\n    \"a\": {\n      \"id\": \"" + sourceID2 + "\",\n      \"encryption\": {\n        \"selector\": \"" + sourceEncryptionSelector + "\",",
		"\"creation\": {\n        \"snapshot\": \"" + sourceID1 + "\",\n        \"nonce\": \"" + sourceID2 + "\"\n      }\n    },\n    \"z\": {",
		"\"secrets\": {\n    \"a\": {\n      \"retained\": {\n        \"incarnation\": \"" + sourceID1 + "\",\n        \"material\": \"" + sourceID2 + "\"\n      }\n    },\n    \"z\": {\n      \"sealed\": \"" + base64.StdEncoding.EncodeToString(envelope) + "\"\n    }\n  },",
		"\"recovery\": {\n      \"enabled\": true,\n      \"signing\": {\n        \"selector\": \"" + sourceSigningSelector + "\",",
	}
	for i, fragment := range fragments {
		if !strings.Contains(out.String(), fragment) {
			t.Fatalf("multiline record alternative %d differs from independent literal", i)
		}
	}
	if !json.Valid(out.Bytes()) || bytes.Contains(out.Bytes(), []byte("\r")) || bytes.Count(out.Bytes(), []byte(base64.StdEncoding.EncodeToString(envelope))) != 1 {
		t.Fatal("generated records are not complete LF-delimited JSON scalars")
	}
}

// full_only: false
func TestStableGeneratedFormattingBudget(t *testing.T) {
	pair := writePair(t, sourceSetupJSON, sourceGeneratedJSON, JSON)
	m, err := Parse(context.Background(), pair)
	if err != nil {
		t.Fatal(err)
	}
	m.RecoveryEnabled, m.Recovery = true, m.Authority
	for i := 0; i < 255; i++ {
		m.Recipients = append(m.Recipients, Recipient{Reference: fmt.Sprintf("r%d", i), ID: m.FileID, Selector: sourceEncryptionSelector, Encryption: m.Authority.Encryption, Creation: &Creation{Snapshot: m.FileID, Nonce: m.DomainID}})
	}
	for i := 0; i < 512; i++ {
		m.Entries = append(m.Entries, Entry{Name: fmt.Sprintf("e%d", i), Secret: true, Retained: &Pin{Incarnation: m.FileID, Material: m.DomainID}})
	}
	m.Basis = Basis{Control: []byte{1}, Selection: []byte{2}}
	for i := 0; i < 256; i++ {
		id := contract.ID{1, byte(i)}
		m.Basis.Enrollment = append(m.Basis.Enrollment, Enrollment{ID: id, Status: contract.CurrentRecipient})
	}
	m.Observation = &Observation{StoreConfiguration: []byte{1}, Head: []byte{2}}
	var out, compact bytes.Buffer
	if err := EmitGenerated(&out, m); err != nil {
		t.Fatal(err)
	}
	if err := json.Compact(&compact, out.Bytes()); err != nil {
		t.Fatal(err)
	}
	// Count each LF, two-space depth and colon space from the closed schema.
	// Root30 + domain321 + recipients(255*156+3) + secrets(512*46+3)
	// + successor(24+3+256*44+5) + observation(18+3) = 75,006.
	if got := out.Len() - compact.Len(); got != 75006 {
		t.Fatalf("ordinary generated formatting bytes %d, want 75006", got)
	}
	// Independent field subtotal + name/path growth + replacement metadata
	// + the ordinary formatting above and replacement formatting112.
	const bound = 252665553 + 84 + 90533 + 75006 + 112
	if bound != 252831288 || MaxPairBytes-int64(bound) != 15604168 {
		t.Fatal("complete emission bound or retained presentation allowance differs")
	}
}

