func TestStableSuppliedRecordInsertion(t *testing.T) {
	for _, name := range []string{"a", "b", "n", "y", "z"} {
		t.Run(name, func(t *testing.T) {
			left := `"b" : { "sealed" : "` + base64.StdEncoding.EncodeToString(sourceEditEnvelope(t, "b")) + `" }`
			right := `"y": {"sealed":"` + base64.StdEncoding.EncodeToString(sourceEditEnvelope(t, "y")) + `"}`
			generated := strings.Replace(stableGeneratedLiteral, `"secrets": {}`, "\"secrets\": {\n    "+left+",\n    "+right+"\n  }", 1)
			pair, err := stablePair(t, stableEditable(YAML, "prod"), generated, YAML, ".enkv/prod.generated.json")
			if err != nil {
				t.Fatal(err)
			}
			m, err := ParseForSet(context.Background(), pair, name)
			if err != nil {
				t.Fatal(err)
			}
			edit, err := PrepareSuppliedEdit(pair, m, name, true, contract.InputEncodingRaw)
			if err != nil {
				t.Fatal(err)
			}
			if unsafe.Sizeof(Span{}) != 64 || unsafe.Sizeof(suppliedSecretRecord{}) != 32 || cap(edit.records) != 512 {
				t.Fatal("record edit workspace exceeds its fixed 64-bit layout")
			}
			// Rows, maximum decoded names, one scalar and fixed parser state fit
			// the transient workspace; scanner/stream windows are charged separately.
			if 512*(unsafe.Sizeof(suppliedSecretRecord{})+256)+256+unsafe.Sizeof(edit.records)+unsafe.Sizeof(parser{}) > 1<<20 {
				t.Fatal("record edit workspace exceeds the transient owner allowance")
			}
			var out bytes.Buffer
			envelope := sourceEditEnvelope(t, name)
			if err := edit.EmitGenerated(context.Background(), &out, envelope); err != nil {
				t.Fatal(err)
			}
			row := `"` + name + `": {` + "\n      \"sealed\": \"" + base64.StdEncoding.EncodeToString(envelope) + "\"\n    }"
			var rows []string
			if name != "b" {
				rows = append(rows, left)
			}
			if name != "y" {
				rows = append(rows, right)
			}
			position := 0
			if name > "b" {
				position++
			}
			if name > "y" {
				position++
			}
			rows = append(rows, "")
			copy(rows[position+1:], rows[position:])
			rows[position] = row
			want := strings.Replace(stableGeneratedLiteral, `"secrets": {}`, "\"secrets\": {\n    "+strings.Join(rows, ",\n    ")+"\n  }", 1)
			if out.String() != want {
				t.Fatal("insertion order, separators, or unchanged encrypted record bytes differ")
			}
			var editable bytes.Buffer
			if err := edit.EmitEditable(context.Background(), &editable, ".enkv/prod.generated.json", nil); err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(editable.String(), "generated: '.enkv/prod.generated.json'\n") {
				t.Fatal("secret edit changed the stable reference token")
			}
		})
	}
}

