func stableEditable(format Format, name string) string {
	quoted, _ := json.Marshal(name)
	if format == JSON {
		return strings.Replace(sourceSetupJSON, `"name":"prod"`, `"name":`+string(quoted), 1)
	}
	return strings.Replace(sourceSetupYAML, "  name: prod\n", "  name: "+string(quoted)+"\n", 1)
}

func stablePair(t *testing.T, editable, generated string, format Format, reference string) (*Pair, error) {
	t.Helper()
	dir := t.TempDir()
	if generated != "" {
		if format == JSON {
			editable = strings.TrimSuffix(editable, "}") + `,"generated":"` + reference + `"}`
		} else {
			editable += "generated: '" + reference + "'\n"
		}
		if err := os.Mkdir(filepath.Join(dir, ".enkv"), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(filepath.Join(dir, reference), []byte(generated), 0600); err != nil {
			t.Fatal(err)
		}
	}
	path := filepath.Join(dir, "chosen-config")
	if err := os.WriteFile(path, []byte(editable), 0600); err != nil {
		t.Fatal(err)
	}
	pair, err := Capture(context.Background(), path, format)
	if err == nil {
		t.Cleanup(func() {
			if err := pair.Close(); err != nil {
				t.Error(err)
			}
		})
	}
	return pair, err
}

// full_only: false
func TestStableDomainNameAndReference(t *testing.T) {
	for _, format := range []Format{JSON, YAML} {
		t.Run(fmt.Sprintf("%d/missing-name", format), func(t *testing.T) {
			editable := strings.Replace(sourceSetupJSON, `"name":"prod",`, "", 1)
			if format == YAML {
				editable = strings.Replace(sourceSetupYAML, "  name: prod\n", "", 1)
			}
			if pair, err := stablePair(t, editable, "", format, ""); err == nil {
				if _, err := Parse(context.Background(), pair); err == nil {
					t.Fatal("accepted absent local domain name")
				}
			}
		})
		for _, name := range []string{"a", "0", "prod_2-us", strings.Repeat("z", 64), "", "A", "-a", "_a", ".", "..", "a/b", `a\b`, "a b", "a\n", "é", strings.Repeat("z", 65)} {
			t.Run(fmt.Sprintf("%d/%q", format, name), func(t *testing.T) {
				valid := name == "a" || name == "0" || name == "prod_2-us" || name == strings.Repeat("z", 64)
				pair, err := stablePair(t, stableEditable(format, name), "", format, "")
				if err == nil {
					_, err = Parse(context.Background(), pair)
				}
				if (err == nil) != valid {
					t.Fatalf("name acceptance %v, want %v: %v", err == nil, valid, err)
				}
			})
		}
		for _, name := range []string{"a", strings.Repeat("z", 64)} {
			t.Run(fmt.Sprintf("%d/resolved/%s", format, name), func(t *testing.T) {
				reference := ".enkv/" + name + ".generated.json"
				pair, err := stablePair(t, stableEditable(format, name), sourceGeneratedJSON, format, reference)
				if err != nil {
					t.Fatal(err)
				}
				m, err := Parse(context.Background(), pair)
				if err != nil || !m.Resolved || m.Generated != reference {
					t.Fatalf("stable reference failed: %v", err)
				}
			})
		}
		t.Run(fmt.Sprintf("%d/mismatch", format), func(t *testing.T) {
			pair, err := stablePair(t, stableEditable(format, "prod"), sourceGeneratedJSON, format, ".enkv/other.generated.json")
			if err == nil {
				_, err = Parse(context.Background(), pair)
			}
			if err == nil {
				t.Fatal("accepted a reference for a different local domain name")
			}
		})
	}
}

