func TestStableHistoricalSealingPredecessor(t *testing.T) {
	envelope := sourceEditEnvelope(t, "item")
	generated := strings.Replace(sourceGeneratedJSON, `"secrets":{}`, `"secrets":{"item":{"sealed":"`+base64.StdEncoding.EncodeToString(envelope)+`"}}`, 1)
	for _, format := range []Format{JSON, YAML} {
		t.Run(fmt.Sprint(format), func(t *testing.T) {
			editable := stableEditable(format, "prod")
			if format == JSON {
				editable = strings.Replace(editable, `"entries":{}`, `"entries":{"item":{"confidentiality":"secret","recipients":[],"source":{"kind":"supplied"}}}`, 1)
			} else {
				editable = strings.Replace(editable, "entries: {}", "# new source comment\nentries: {item: {confidentiality: secret, recipients: [], source: {kind: supplied}}}", 1)
			}
			pair, err := stablePair(t, editable, generated, format, ".enkv/prod.generated.json")
			if err != nil {
				t.Fatal(err)
			}
			m, err := Parse(context.Background(), pair)
			if err != nil || len(m.Entries) != 1 || !bytes.Equal(m.Entries[0].Sealed, envelope) {
				t.Fatalf("historical sealed record changed or refused: %v", err)
			}
			view, err := contract.InspectSealedInputEnvelope(m.Entries[0].Sealed)
			if err != nil || view.Core.FilePredecessorDigest[0] != 1 || [32]byte(view.Core.FilePredecessorDigest) == pair.Editable.Digest() {
				t.Fatal("sealing predecessor was retargeted to current presentation")
			}
		})
	}
}

// full_only: false
func TestStableEditableFilenameIndependence(t *testing.T) {
	for i := 0; i < 2; i++ {
		pair, err := stablePair(t, stableEditable(JSON, "prod"), sourceGeneratedJSON, JSON, ".enkv/prod.generated.json")
		if err != nil {
			t.Fatal(err)
		}
		before, err := Parse(context.Background(), pair)
		if err != nil {
			t.Fatal(err)
		}
		path := filepath.Join(filepath.Dir(pair.Editable.OriginalPath()), "another-name.json")
		if err := os.Rename(pair.Editable.OriginalPath(), path); err != nil {
			t.Fatal(err)
		}
		afterPair, err := Capture(context.Background(), path, JSON)
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() {
			if err := afterPair.Close(); err != nil {
				t.Error(err)
			}
		})
		after, err := Parse(context.Background(), afterPair)
		if err != nil || after.Generated != before.Generated || after.DomainID != before.DomainID || after.FileID != before.FileID || afterPair.Generated.Digest() != pair.Generated.Digest() {
			t.Fatalf("editable rename changed stable identity: %v", err)
		}
		if _, err := io.Copy(io.Discard, io.NewSectionReader(afterPair.Generated, 0, afterPair.Generated.Size())); err != nil {
			t.Fatal(err)
		}
	}
}
