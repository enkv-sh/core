// The stored output declaration is exactly 32 MiB, with 256-byte source names.
// full_only: true
func TestEditableEmissionPreservesMaximumStoredOutputDeclaration(t *testing.T) {
	m, err := Parse(context.Background(), writePair(t, sourceSetupJSON, sourceGeneratedJSON, JSON))
	if err != nil {
		t.Fatal(err)
	}
	binding := outputStoredBoundaryBinding(256)
	m.Outputs = []OutputBinding{{DestinationID: "d", Binding: binding}}
	m.Routes = []Route{{Default: true, Destinations: []string{"d"}}}
	for _, target := range binding.Targets {
		m.Entries = append(m.Entries, Entry{Name: target.Name})
	}
	for _, format := range []Format{JSON, YAML} {
		t.Run(map[Format]string{JSON: "json", YAML: "yaml"}[format], func(t *testing.T) {
			var editable, generated bytes.Buffer
			if err := EmitEditable(&editable, m, format); err != nil {
				t.Fatal("valid stored declaration could not be emitted", err)
			}
			if err := EmitGenerated(&generated, m); err != nil {
				t.Fatal(err)
			}
			if int64(editable.Len())+int64(generated.Len()) > MaxPairBytes {
				t.Fatal("supported output declaration exceeds complete pair bound")
			}
			pair := captureEditableEmission(t, editable.Bytes(), generated.Bytes(), format, m.Generated)
			again, err := Parse(context.Background(), pair)
			if err != nil {
				t.Fatal("emitted maximum declaration did not reparse", err)
			}
			if len(again.Outputs) != 1 || !reflect.DeepEqual(again.Outputs[0].Binding, binding) || len(again.Entries) != 64 || len(again.Routes) != 1 || !reflect.DeepEqual(again.Routes[0].Destinations, []string{"d"}) {
				t.Fatal("maximum output declaration meaning changed")
			}
			for i, row := range again.Outputs[0].Binding.Targets {
				if len(row.Name) != contract.CryptoMaxName || again.Entries[i].Name != row.Name || len(again.Entries[i].Plain) != 0 || again.Entries[i].Secret {
					t.Fatal("long entry name or empty plain value changed")
				}
			}
		})
	}
}

// full_only: false
func TestEditableEmissionPreservesCompleteSourceMeaning(t *testing.T) {
	for _, retirement := range []string{"manual", "auto"} {
		t.Run(retirement, func(t *testing.T) {
			entries := `"entries":{"":{"confidentiality":"plain","recipients":[],"source":{"kind":"supplied","value":""}},"a/\n雪":{"confidentiality":"plain","recipients":[],"source":{"kind":"supplied","bytes":"/wBB"}},"generated":{"confidentiality":"secret","recipients":[],"source":{"kind":"generated","plugin":"private-generator","epoch":18446744073709551615,"retirement":"` + retirement + `","settings":` + pluginSettings + `}},"retained":{"confidentiality":"secret","recipients":[],"source":{"kind":"supplied"}}}`
			editable := strings.Replace(sourceSetupJSON, `"entries":{}`, entries, 1)
			generated := strings.Replace(sourceGeneratedJSON, `"secrets":{}`, `"secrets":{"retained":{"retained":{"incarnation":"`+sourceID4+`","material":"`+sourceID5+`"}}}`, 1)
			m, err := Parse(context.Background(), writePair(t, editable, generated, JSON))
			if err != nil {
				t.Fatal(err)
			}

			for _, format := range []Format{JSON, YAML} {
				t.Run(map[Format]string{JSON: "json", YAML: "yaml"}[format], func(t *testing.T) {
					var declaration, satellite bytes.Buffer
					if err := EmitEditable(&declaration, m, format); err != nil {
						t.Fatal(err)
					}
					if err := EmitGenerated(&satellite, m); err != nil {
						t.Fatal(err)
					}
					pair := captureEditableEmission(t, declaration.Bytes(), satellite.Bytes(), format, m.Generated)
					again, err := Parse(context.Background(), pair)
					if err != nil {
						t.Fatal(err)
					}
					if !reflect.DeepEqual(again.Public, m.Public) || !reflect.DeepEqual(again.Basis, m.Basis) || again.DomainName != "prod" || again.FileID != m.FileID || !reflect.DeepEqual(again.Observation, m.Observation) {
						t.Fatal("complete pair meaning changed")
					}
					for _, e := range again.Entries {
						switch e.Name {
						case "":
							if e.Secret || len(e.Plain) != 0 {
								t.Fatal("empty name/value changed")
							}
						case "a/\n雪":
							if !bytes.Equal(e.Plain, []byte{255, 0, 65}) {
								t.Fatal("binary plain bytes changed")
							}
						case "generated":
							if e.Generated == nil || e.Generated.Epoch != ^uint64(0) || e.Generated.Retirement != retirement || !bytes.Equal(e.Generated.Settings, []byte(pluginSettings)) {
								t.Fatal("complete generated settings changed")
							}
						case "retained":
							if e.Retained == nil || hex.EncodeToString(e.Retained.Incarnation[:]) != sourceID4 || hex.EncodeToString(e.Retained.Material[:]) != sourceID5 || len(e.Sealed) != 0 {
								t.Fatal("retained secret was lost or resealed")
							}
						}
					}
					if format == JSON {
						var got struct {
							Entries map[string]struct{ Source struct{ Settings any } }
						}
						var want any
						if err := json.Unmarshal(declaration.Bytes(), &got); err != nil {
							t.Fatal(err)
						}
						const canonicalSource = pluginSettings
						if err := json.Unmarshal([]byte(canonicalSource), &want); err != nil {
							t.Fatal(err)
						}
						if !reflect.DeepEqual(got.Entries["generated"].Source.Settings, want) {
							t.Fatal("opaque source settings differ")
						}
					}
				})
			}
		})
	}
}

func captureEditableEmission(t *testing.T, declaration, satellite []byte, format Format, reference string) *Pair {
	t.Helper()
	dir := t.TempDir()
	if err := os.Mkdir(filepath.Join(dir, ".enkv"), 0700); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, reference), satellite, 0600); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(dir, "configuration")
	if err := os.WriteFile(path, declaration, 0600); err != nil {
		t.Fatal(err)
	}
	pair, err := Capture(context.Background(), path, format)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() {
		if err := pair.Close(); err != nil {
			t.Error(err)
		}
	})
	return pair
}

// full_only: false
func TestEditableEmissionRefusesInvalidModelsAndPreservesWriteErrors(t *testing.T) {
	m, err := Parse(context.Background(), writePair(t, sourceSetupJSON, sourceGeneratedJSON, JSON))
	if err != nil {
		t.Fatal(err)
	}
	if err := EmitEditable(&shortGeneratedWriter{}, m, JSON); !errors.Is(err, io.ErrShortWrite) {
		t.Fatal("short write cause lost", err)
	}
	for _, name := range []string{"", "../prod", "a/b"} {
		if _, err := GeneratedPath(name); err == nil {
			t.Fatal("invalid local name accepted")
		}
	}
	for _, mutate := range []func(*Model){func(v *Model) { v.Resolved = false }, func(v *Model) { v.Generated = ".enkv/other.generated.json" }, func(v *Model) { v.DomainName = "../prod" }} {
		copy := *m
		mutate(&copy)
		if err := EmitEditable(io.Discard, &copy, JSON); err == nil {
			t.Fatal("invalid model emitted")
		}
	}
}

// full_only: false
func TestEditableSettingsUseReadableTypedLayout(t *testing.T) {
	const settings = `{"text":"雪\n\u0001","number":12345678901234567890.00e-2,"boolean":true,"null":null,"empty":{},"array":["---","...",[],{"n":-0}]}`
	// These expected sections follow the documented two-space layout directly.
	const yaml = `settings:
  text: "雪\n\u0001"
  number: 12345678901234567890.00e-2
  boolean: true
  "null": null
  empty: {}
  array:
    - ---
    - ...
    - []
    -
      n: -0
`
	const json = `"settings": {
    "text": "雪\n\u0001",
    "number": 12345678901234567890.00e-2,
    "boolean": true,
    "null": null,
    "empty": {},
    "array": [
      "---",
      "...",
      [],
      {
        "n": -0
      }
    ]
  }`
	for _, tc := range []struct {
		format Format
		want   string
	}{{YAML, yaml}, {JSON, json}} {
		t.Run(fmt.Sprint(tc.format), func(t *testing.T) {
			var out bytes.Buffer
			w := &editableWriter{generatedWriter: generatedWriter{out: &out}, format: tc.format}
			w.level = 1
			w.frames[0].first = true
			w.settings([]byte(settings), 1024)
			got := out.String()
			if tc.format == JSON {
				got = strings.TrimPrefix(got, "\n  ")
			}
			if w.err != nil || got != tc.want {
				t.Fatalf("readable settings differ:\n%s\nerror: %v", got, w.err)
			}
		})
	}
}
