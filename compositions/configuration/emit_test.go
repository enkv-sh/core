// full_only: false
func TestGeneratedEmissionAndPublicTransfer(t *testing.T) {
	pair := writePair(t, sourceSetupJSON, sourceGeneratedJSON, JSON)
	m, e := Parse(context.Background(), pair)
	if e != nil {
		t.Fatal(e)
	}
	var encoded bytes.Buffer
	if e = EmitGenerated(&encoded, m); e != nil {
		t.Fatal(e)
	}
	if encoded.String() != stableGeneratedLiteral {
		t.Fatal("complete generated bytes differ from independently specified literal")
	}
	again := writePair(t, sourceSetupJSON, encoded.String(), JSON)
	other, e := Parse(context.Background(), again)
	if e != nil {
		t.Fatal(e)
	}
	if !reflect.DeepEqual(other.Public, m.Public) || !reflect.DeepEqual(other.Basis, m.Basis) {
		t.Fatal("emission changed complete public/basis meaning")
	}
	public, basis := m.TakePublic()
	if !reflect.DeepEqual(*m, Model{}) || len(public.Recipients.Value) != 1 || !bytes.Equal(basis.Descriptor, []byte{1}) {
		t.Fatal("public transfer retained source-only owner or lost public input")
	}
	m = other
	bad := &shortGeneratedWriter{}
	if e = EmitGenerated(bad, m); e == nil || !errors.Is(e, io.ErrShortWrite) {
		t.Fatal("writer failure not preserved")
	}
}

type shortGeneratedWriter struct{}

func (*shortGeneratedWriter) Write(b []byte) (int, error) {
	if len(b) > 1 {
		return 1, io.ErrShortWrite
	}
	return 0, io.ErrShortWrite
}

// full_only: false
func TestSourceSpansPreserveUnrelatedSyntax(t *testing.T) {
	entries := "entries:\n  first:\n    confidentiality: plain\n    recipients: []\n    source:\n      kind: supplied\n      value: old # keep value comment\n  # keep next entry comment\n  second: {confidentiality: plain, recipients: [], source: {kind: supplied, value: other}}"
	editable := strings.Replace(sourceSetupYAML, "entries: {}", entries, 1)
	pair := writePair(t, editable, "", YAML)
	m, e := Parse(context.Background(), pair)
	if e != nil {
		t.Fatal(e)
	}
	span := m.Spans[m.Entries[0].EntrySpan]
	if span.Kind != SpanEntry || int(span.ValueOffset)+int(span.ValueLength) > len(editable) || editable[span.ValueOffset:span.ValueOffset+span.ValueLength] != "old" {
		t.Fatalf("wrong selected scalar span %+v", span)
	}
	modified := editable[:span.ValueOffset] + `"new"` + editable[span.ValueOffset+span.ValueLength:]
	want := strings.Replace(editable, "value: old #", "value: \"new\" #", 1)
	if modified != want {
		t.Fatal("scalar span captured unrelated comments/whitespace")
	}
	resolved := writePair(t, sourceSetupJSON, sourceGeneratedJSON, JSON)
	m, e = Parse(context.Background(), resolved)
	if e != nil {
		t.Fatal(e)
	}
	var image bytes.Buffer
	if _, e = resolved.Editable.CopyTo(&image); e != nil {
		t.Fatal(e)
	}
	reference := m.Spans[m.GeneratedSpan]
	if reference.Kind != SpanGeneratedReference || image.String()[reference.Offset:reference.Offset+reference.Length] != strconv.Quote(m.Generated) {
		t.Fatal("generated reference span differs")
	}
	if cap(m.Spans) > MaxSpans {
		t.Fatal("index backing exceeds account")
	}
}
