func TestRecipientSourceIdentityJoins(t *testing.T) {
	for _, format := range []Format{JSON, YAML} {
		for _, condition := range []string{"matching", "missing", "different", "duplicate", "zero", "uppercase", "authority", "unprepared"} {
			t.Run(fmt.Sprintf("%d/%s", format, condition), func(t *testing.T) {
				id := preparedSourceRecipientID
				switch condition {
				case "different":
					id = sourceID5
				case "zero":
					id = strings.Repeat("00", 32)
				case "uppercase":
					id = strings.Repeat("AB", 32)
				case "authority":
					id = sourceID3
				}
				declaration := `{"id":"` + id + `","display_name":"","encryption_key":"` + sourceEncryptionSelector + `"}`
				if condition == "missing" || condition == "unprepared" {
					declaration = `{"display_name":"","encryption_key":"` + sourceEncryptionSelector + `"}`
				}
				recipients := `{"chosen":` + declaration + `}`
				generated := strings.Replace(sourceGeneratedJSON, `"recipients":{}`, `"recipients":{"chosen":`+preparationRecipientRow()+`}`, 1)
				if condition == "duplicate" {
					recipients = `{"chosen":` + declaration + `,"other":` + declaration + `}`
					other := strings.Replace(preparationRecipientRow(), preparedSourceRecipientID, sourceID5, 1)
					generated = strings.Replace(generated, `"recipients":{`, `"recipients":{"other":`+other+`,`, 1)
				}
				if condition == "unprepared" {
					generated = ""
				}
				pair := captureRecipientIdentityImages(t, preparationEditable(format, recipients), generated, format)
				model, err := Parse(t.Context(), pair)
				if condition == "matching" || condition == "unprepared" {
					if err != nil || len(model.Recipients) != 1 {
						t.Fatal("valid recipient source identity refused", err)
					}
					if condition == "matching" && hex.EncodeToString(model.Recipients[0].ID[:]) != preparedSourceRecipientID {
						t.Fatal("source identity changed during companion join")
					}
					return
				}
				if err == nil || model != nil {
					t.Fatal("invalid or missing source identity admitted")
				}
				if selected, err := ParseForRecipientPreparation(t.Context(), pair, "chosen"); err == nil || selected != nil {
					t.Fatal("selected preparation hid a source identity conflict")
				}
			})
		}
	}
}

