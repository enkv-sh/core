func TestRecipientPreparationWritesSourceIdentity(t *testing.T) {
	for _, format := range []Format{JSON, YAML} {
		for _, declare := range []bool{false, true} {
			t.Run(fmt.Sprintf("%d/declare-%t", format, declare), func(t *testing.T) {
				recipients := `{"chosen":{"display_name":"","encryption_key":"` + sourceEncryptionSelector + `"}}`
				var declaration *RecipientDeclaration
				if declare {
					recipients = `{}`
					declaration = &RecipientDeclaration{EncryptionSelector: sourceEncryptionSelector}
				}
				pair := writePair(t, preparationEditable(format, recipients), sourceGeneratedJSON, format)
				model, err := ParseForRecipientPreparation(t.Context(), pair, "chosen")
				if err != nil {
					t.Fatal(err)
				}
				material := preparationMaterial(t)
				edit, err := PrepareRecipientEdit(t.Context(), pair, model, "chosen", declaration, material)
				if err != nil {
					t.Fatal(err)
				}
				var editable, generated bytes.Buffer
				if err := edit.EmitEditable(t.Context(), &editable, model.Generated); err != nil {
					t.Fatal(err)
				}
				if err := edit.EmitGenerated(t.Context(), &generated); err != nil {
					t.Fatal(err)
				}
				candidate := captureEditableEmission(t, editable.Bytes(), generated.Bytes(), format, model.Generated)
				source, err := parseEditableMode(t.Context(), candidate.Editable, format, false, nil)
				if err != nil || len(source.Recipients) != 1 || source.Recipients[0].ID != material.RecipientID {
					t.Fatal("recipient preparation did not write the allocated source ID", err)
				}
				if _, err := Parse(t.Context(), candidate); err != nil {
					t.Fatal("prepared source ID did not join the companion", err)
				}
			})
		}
	}
}

