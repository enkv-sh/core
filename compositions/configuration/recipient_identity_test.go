func TestRecipientSourceIdentitySurvivesEmissionAndRename(t *testing.T) {
	for _, format := range []Format{JSON, YAML} {
		t.Run(fmt.Sprint(format), func(t *testing.T) {
			recipients := `{"chosen":{"id":"` + preparedSourceRecipientID + `","display_name":"","encryption_key":"` + sourceEncryptionSelector + `"}}`
			generated := strings.Replace(sourceGeneratedJSON, `"recipients":{}`, `"recipients":{"chosen":`+preparationRecipientRow()+`}`, 1)
			pair := writePair(t, preparationEditable(format, recipients), generated, format)
			model, err := Parse(t.Context(), pair)
			if err != nil {
				t.Fatal(err)
			}
			var emitted bytes.Buffer
			if err := EmitEditable(&emitted, model, format); err != nil {
				t.Fatal(err)
			}
			fresh := captureEditableEmission(t, emitted.Bytes(), []byte(generated), format, model.Generated)
			source, err := parseEditableMode(t.Context(), fresh.Editable, format, false, nil)
			if err != nil || len(source.Recipients) != 1 || hex.EncodeToString(source.Recipients[0].ID[:]) != preparedSourceRecipientID {
				t.Fatal("fresh source emission lost recipient identity", err)
			}
			edit, err := PrepareRecipientReferenceEdit(t.Context(), pair, "chosen", "renamed")
			if err != nil {
				t.Fatal(err)
			}
			var editable, companion bytes.Buffer
			if err := edit.EmitEditable(t.Context(), &editable, model.Generated); err != nil {
				t.Fatal(err)
			}
			if err := edit.EmitGenerated(t.Context(), &companion); err != nil {
				t.Fatal(err)
			}
			renamed, err := Parse(t.Context(), captureEditableEmission(t, editable.Bytes(), companion.Bytes(), format, model.Generated))
			if err != nil || len(renamed.Recipients) != 1 || renamed.Recipients[0].Reference != "renamed" || hex.EncodeToString(renamed.Recipients[0].ID[:]) != preparedSourceRecipientID {
				t.Fatal("reference rename changed recipient identity", err)
			}
		})
	}
}

