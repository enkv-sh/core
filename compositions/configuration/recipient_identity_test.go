func TestRecipientIdentityInsertionPreservesYAMLSource(t *testing.T) {
	for _, layout := range []string{"block", "block-crlf", "flow-trailing"} {
		t.Run(layout, func(t *testing.T) {
			declaration := "  chosen:\n    # keep recipient comment\n    display_name: '' # keep display comment\n    encryption_key: " + sourceEncryptionSelector
			if layout == "flow-trailing" {
				declaration = `{chosen: {display_name: '', encryption_key: ` + sourceEncryptionSelector + `,}} # keep recipient comment`
			}
			recipients := "recipients:\n" + declaration
			if layout == "flow-trailing" {
				recipients = "recipients: " + declaration
			}
			body := strings.Replace(sourceSetupYAML, "recipients: {}", recipients, 1)
			if layout == "block-crlf" {
				body = strings.ReplaceAll(body, "\n", "\r\n")
			}
			pair := writePair(t, body, sourceGeneratedJSON, YAML)
			model, err := ParseForRecipientPreparation(t.Context(), pair, "chosen")
			if err != nil {
				t.Fatal(err)
			}
			material := preparationMaterial(t)
			edit, err := PrepareRecipientEdit(t.Context(), pair, model, "chosen", nil, material)
			if err != nil {
				t.Fatal(err)
			}
			var source, companion bytes.Buffer
			if err := edit.EmitEditable(t.Context(), &source, model.Generated); err != nil {
				t.Fatal(err)
			}
			if err := edit.EmitGenerated(t.Context(), &companion); err != nil {
				t.Fatal(err)
			}
			original := readSource(t, pair.Editable.OriginalPath())
			want := strings.Replace(original, "    display_name: '' # keep display comment", `    id: "`+preparedSourceRecipientID+"\"\n    display_name: '' # keep display comment", 1)
			if layout == "flow-trailing" {
				want = strings.Replace(original, "chosen: {", `chosen: {id: "`+preparedSourceRecipientID+`",`, 1)
			}
			if source.String() != want {
				t.Fatal("ID insertion changed unrelated YAML source bytes")
			}
			after, err := Parse(t.Context(), captureEditableEmission(t, source.Bytes(), companion.Bytes(), YAML, model.Generated))
			if err != nil || len(after.Recipients) != 1 || after.Recipients[0].ID != material.RecipientID {
				t.Fatal("ID insertion did not produce a valid complete pair", err)
			}
		})
	}
}
