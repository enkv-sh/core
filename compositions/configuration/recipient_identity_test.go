const preparedSourceRecipientID = "0606060606060606060606060606060606060606060606060606060606060606"

func captureRecipientIdentityImages(t *testing.T, editable, generated string, format Format) *Pair {
	t.Helper()
	directory := t.TempDir()
	if generated != "" {
		if format == JSON {
			editable = strings.TrimSuffix(editable, "}") + `,"generated":".enkv/prod.generated.json"}`
		} else {
			editable += "generated: '.enkv/prod.generated.json'\n"
		}
	}
	pair := &Pair{Format: format}
	for _, image := range []struct {
		body string
		dst  **Image
		name string
	}{{editable, &pair.Editable, "configuration"}, {generated, &pair.Generated, ".enkv/prod.generated.json"}} {
		if image.body == "" {
			continue
		}
		path := filepath.Join(directory, image.name)
		if err := os.MkdirAll(filepath.Dir(path), 0700); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(image.body), 0600); err != nil {
			t.Fatal(err)
		}
		captured, err := capture(t.Context(), path, MaxPairBytes)
		if err != nil {
			t.Fatal(err)
		}
		*image.dst = captured
	}
	t.Cleanup(func() { closeSourceOwner(t, pair) })
	// Parser-owner cases retain coherent captured images without asking the
	// earlier source-capture parser to accept intentionally invalid source.
	if err := sealPair(pair); err != nil {
		t.Fatal(err)
	}
	return pair
}

