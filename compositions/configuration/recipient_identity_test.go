func TestRecipientSourceIdentityCapacity(t *testing.T) {
	for _, count := range []int{255, 256} {
		t.Run(fmt.Sprint(count), func(t *testing.T) {
			var source, generated strings.Builder
			source.WriteByte('{')
			generated.WriteByte('{')
			for i := range count {
				if i != 0 {
					source.WriteByte(',')
					generated.WriteByte(',')
				}
				// Public IDs use independent fixed-width integer encodings, with
				// no overlap with the fixture's repeated-byte Authority ID.
				id := fmt.Sprintf("%064x", i+1)
				fmt.Fprintf(&source, `"r%03d":{"id":"%s","display_name":"","encryption_key":"%s"}`, i, id, sourceEncryptionSelector)
				fmt.Fprintf(&generated, `"r%03d":%s`, i, strings.Replace(preparationRecipientRow(), preparedSourceRecipientID, id, 1))
			}
			source.WriteByte('}')
			generated.WriteByte('}')
			companion := strings.Replace(sourceGeneratedJSON, `"recipients":{}`, `"recipients":`+generated.String(), 1)
			pair := captureRecipientIdentityImages(t, preparationEditable(JSON, source.String()), companion, JSON)
			model, err := Parse(t.Context(), pair)
			if count == 256 {
				if err == nil || model != nil {
					t.Fatal("recipient source ID exceeded the existing recipient limit")
				}
				return
			}
			if err != nil || len(model.Recipients) != 255 || len(model.Spans) > MaxSpans || MaxSpans != 8192 {
				t.Fatal("maximum recipient source IDs exceeded bounded metadata", err)
			}
			for i, recipient := range model.Recipients {
				if recipient.Reference != fmt.Sprintf("r%03d", i) || hex.EncodeToString(recipient.ID[:]) != fmt.Sprintf("%064x", i+1) {
					t.Fatal("maximum source IDs lost an exact recipient association")
				}
				span, err := modelSpan(model, recipient.IDSpan)
				if err != nil || span.Length != 66 {
					t.Fatal("source ID token lost its bounded span", err)
				}
			}
		})
	}
}

