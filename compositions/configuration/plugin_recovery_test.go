// full_only: false
func TestCanonicalPluginRecoveryPreservesExactMeaning(t *testing.T) {
	body, err := hex.DecodeString(canonicalOutputLiteral)
	if err != nil {
		t.Fatal(err)
	}
	intent := sourceCanonicalIntent(t, true)
	entries := `"entries":{"token":{"confidentiality":"secret","recipients":[],"source":{"kind":"generated","plugin":null,"epoch":7,"retirement":"manual","canonical":{"settings":{}}}}}`
	outputs := `"outputs":{"destinations":{"private":{"plugin":null,"canonical":{"settings":{"n":1.00}}}},"routing":{"default":["private"]}}`
	editable := strings.Replace(sourceSetupJSON, `"entries":{}`, entries, 1)
	editable = strings.Replace(editable, `"outputs":{"destinations":{},"routing":{}}`, outputs, 1)
	model, err := Parse(t.Context(), writePair(t, editable, sourceGeneratedCanonical(t, map[string][]byte{"token": intent}, map[string][]byte{"private": body}), JSON))
	if err != nil {
		t.Fatal(err)
	}
	if len(model.Outputs) != 1 || model.Outputs[0].Plugin != "" || model.Outputs[0].Settings != nil {
		t.Fatal("recovery invented plugin selection")
	}
	target := model.Public.OutputBindings.Value[0].Targets.Value[0]
	if target.ConsumerLocator.Value != "" || !target.LocatorRequiresCreation.Value || !bytes.Equal(target.TargetData.Value, []byte{255, 0}) || string(model.Outputs[0].Binding.Destination.CanonicalSettings) != `{"n":1.00}` {
		t.Fatal("stored canonical target or settings changed")
	}
	for _, format := range []Format{JSON, YAML} {
		var editable, generated bytes.Buffer
		if err := EmitEditable(&editable, model, format); err != nil {
			t.Fatal(err)
		}
		if err := EmitGenerated(&generated, model); err != nil {
			t.Fatal(err)
		}
		if bytes.Contains(editable.Bytes(), []byte(base64.StdEncoding.EncodeToString(body))) || !bytes.Contains(generated.Bytes(), []byte(base64.StdEncoding.EncodeToString(body))) {
			t.Fatal("complete canonical output carrier changed")
		}
		again, err := Parse(t.Context(), captureEditableEmission(t, editable.Bytes(), generated.Bytes(), format, model.Generated))
		if err != nil || !reflect.DeepEqual(again.Public, model.Public) {
			t.Fatal("plugin-free canonical round trip changed meaning", err)
		}
	}
}

