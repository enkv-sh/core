func TestOutputSourceDistinguishesUnavailableAndEmptyTargets(t *testing.T) {
	for name, generated := range map[string]string{"setup": "", "resolved": sourceGeneratedJSON} {
		t.Run(name, func(t *testing.T) {
			editable := strings.Replace(sourceSetupJSON, `"destinations":{}`, `"destinations":{"private":{"plugin":"private-output","settings":{"n":1}}}`, 1)
			model, err := Parse(t.Context(), writePair(t, editable, generated, JSON))
			if err != nil {
				t.Fatal(err)
			}
			if model.Public.OutputBindings.State != contract.PublicPresent || len(model.Public.OutputBindings.Value) != 1 {
				t.Fatal("source output binding facts missing")
			}
			if model.Public.OutputBindings.Value[0].Destination.State != contract.PublicUnavailable || model.Public.OutputBindings.Value[0].Targets.State != contract.PublicUnavailable {
				t.Fatal("raw settings claimed normalized meaning")
			}
			model.Outputs[0].Binding.Destination = contract.OutputDestination{ConfigContractID: "private-config", ServiceContractID: "private-service", CanonicalSettings: []byte(`{"n":1}`)}
			if err := RefreshPublic(model); err != nil {
				t.Fatal(err)
			}
			if model.Public.OutputBindings.Value[0].Destination.State != contract.PublicPresent || model.Public.OutputBindings.Value[0].Targets.State != contract.PublicUnavailable {
				t.Fatal("destination normalization invented complete targets")
			}
			model.Outputs[0].Binding.Targets = []contract.NormalOutputTarget{}
			if err := RefreshPublic(model); err != nil {
				t.Fatal(err)
			}
			if model.Public.OutputBindings.Value[0].Targets.State != contract.PublicPresent || model.Public.OutputBindings.Value[0].Targets.Value == nil {
				t.Fatal("complete empty target set became unavailable")
			}
		})
	}
}

