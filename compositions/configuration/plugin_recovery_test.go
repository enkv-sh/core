func TestCanonicalOutputSourceRejectsCompetingOrMismatchedFields(t *testing.T) {
	body, err := hex.DecodeString(canonicalOutputLiteral)
	if err != nil {
		t.Fatal(err)
	}
	carrier := `{"plugin":null,"canonical":{"settings":{"n":1.00}}}`
	for name, source := range map[string]string{
		"renamed":               `{"destinations":{"other":` + carrier + `},"routing":{}}`,
		"outer-encodings":       `{"destinations":{"private":` + strings.TrimSuffix(carrier, "}") + `,"encodings":{}}},"routing":{}}`,
		"extra-canonical-field": `{"destinations":{"private":` + strings.Replace(carrier, `"settings":`, `"schema":1,"settings":`, 1) + `},"routing":{}}`,
	} {
		t.Run(name, func(t *testing.T) {
			p := newParser(t.Context(), strings.NewReader(source), JSON)
			model := &Model{}
			parseOutputs(p, model)
			err := p.done()
			if err == nil {
				records := newParser(t.Context(), strings.NewReader(`{"generators":{},"outputs":{"private":"`+base64.StdEncoding.EncodeToString(body)+`"}}`), JSON)
				parseCanonicalRecords(records, model)
				err = records.done()
			}
			if err == nil {
				err = resolveCanonicalSettings(model)
			}
			if err == nil {
				t.Fatal("invalid canonical source accepted")
			}
		})
	}
}
