const sourcePluginRequirements = `{"generic-json":{"version":"1.2.3"},"aws-secrets-manager":{}}`

func sourceWithPlugins(source string, format Format, requirements string) string {
	if format == JSON {
		return strings.Replace(source, `"schema":`, `"plugins":`+requirements+`,"schema":`, 1)
	}
	return "plugins: " + requirements + "\n" + source
}

func requirePreservedPlugins(t *testing.T, editable []byte) {
	t.Helper()
	if !bytes.Contains(editable, []byte(sourcePluginRequirements)) {
		t.Fatal("source plugin requirements changed")
	}
}

func pairWithPluginRequirements(t *testing.T, pair *Pair, format Format) *Pair {
	t.Helper()
	editable := sourceWithPlugins(string(maintenanceImageBytes(t, pair.Editable)), format, sourcePluginRequirements)
	return captureEditableEmission(t, []byte(editable), maintenanceImageBytes(t, pair.Generated), format, ".enkv/prod.generated.json")
}

func emittedPlugins(t *testing.T, model *Model) map[string]map[string]string {
	t.Helper()
	var body bytes.Buffer
	if err := EmitEditable(&body, model, JSON); err != nil {
		t.Fatal(err)
	}
	var declaration struct {
		Plugins map[string]map[string]string `json:"plugins"`
	}
	if err := json.Unmarshal(body.Bytes(), &declaration); err != nil {
		t.Fatal(err)
	}
	return declaration.Plugins
}

// full_only: false
func TestPluginRequirementsParseAndEmission(t *testing.T) {
	const allNames = `{"cloudflare-account-token":{},"local-random-secret":{},"aws-secrets-manager":{},"gcp-secret-manager":{},"github-actions-repository":{},"github-actions-organization":{},"github-actions-environment":{},"generic-json":{},"opentofu-tfvars-json":{},"private-not-published":{}}`
	maximumVersion := "1.2.3+" + strings.Repeat("a", 122)
	for _, encoding := range []Format{JSON, YAML} {
		for _, tc := range []struct{ name, requirements string }{
			{"empty", `{}`},
			{"pinned-and-unpinned", sourcePluginRequirements},
			{"independent-names", allNames},
			{"prerelease", `{"generic-json":{"version":"1.2.3-rc.1+build.4"}}`},
			{"maximum-version", `{"generic-json":{"version":"` + maximumVersion + `"}}`},
			{"maximum-private-name", `{"` + strings.Repeat("p", 255) + `":{}}`},
		} {
			t.Run(map[Format]string{JSON: "json", YAML: "yaml"}[encoding]+"/"+tc.name, func(t *testing.T) {
				setup := sourceSetupJSON
				if encoding == YAML {
					setup = sourceSetupYAML
				}
				base, err := Parse(t.Context(), writePair(t, setup, sourceGeneratedJSON, encoding))
				if err != nil {
					t.Fatal(err)
				}
				model, err := Parse(t.Context(), writePair(t, sourceWithPlugins(setup, encoding, tc.requirements), sourceGeneratedJSON, encoding))
				if err != nil {
					t.Fatal("valid source plugin requirements refused", err)
				}
				if !reflect.DeepEqual(model.Public, base.Public) {
					t.Fatal("source plugin requirements changed public domain meaning")
				}
				plugins := slices.Clone(model.Plugins)
				var want map[string]map[string]string
				if err := json.Unmarshal([]byte(tc.requirements), &want); err != nil {
					t.Fatal(err)
				}
				var names []string
				for name := range want {
					names = append(names, name)
				}
				slices.Sort(names)
				for _, outputFormat := range []Format{JSON, YAML} {
					var editable, generated, baseGenerated bytes.Buffer
					if err := EmitEditable(&editable, model, outputFormat); err != nil {
						t.Fatal(err)
					}
					previous := -1
					for _, name := range names {
						key := strconv.Quote(name)
						if outputFormat == YAML {
							key = name
						}
						position := bytes.Index(editable.Bytes(), []byte(key+":"))
						if position <= previous {
							t.Fatal("emitted plugin keys are missing or not in name order", name)
						}
						previous = position
					}
					if err := EmitGenerated(&generated, model); err != nil {
						t.Fatal(err)
					}
					if err := EmitGenerated(&baseGenerated, base); err != nil {
						t.Fatal(err)
					}
					if !bytes.Equal(generated.Bytes(), baseGenerated.Bytes()) {
						t.Fatal("source plugin requirements entered generated satellite")
					}
					again, err := Parse(t.Context(), captureEditableEmission(t, editable.Bytes(), generated.Bytes(), outputFormat, model.Generated))
					if err != nil {
						t.Fatal(err)
					}
					got := emittedPlugins(t, again)
					if len(want) == 0 && len(got) == 0 {
						continue
					}
					if !reflect.DeepEqual(got, want) {
						t.Fatal("emission changed plugin requirements", got, want)
					}
				}
				if !slices.Equal(model.Plugins, plugins) {
					t.Fatal("emission changed the source-owned requirements")
				}
				public, _ := model.TakePublic()
				if !reflect.DeepEqual(public, base.Public) || !reflect.DeepEqual(*model, Model{}) {
					t.Fatal("public transfer retained source-only owners or changed public facts")
				}
			})
		}
	}
}

