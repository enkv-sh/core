func TestPluginRequirementsEmissionRefusesInvalidModels(t *testing.T) {
	model, err := Parse(t.Context(), writePair(t, sourceSetupJSON, sourceGeneratedJSON, JSON))
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		name         string
		requirements []PluginRequirement
	}{
		{"unsafe-name", []PluginRequirement{{Name: "../unknown"}}},
		{"duplicate-name", []PluginRequirement{{Name: "generic-json"}, {Name: "generic-json", Version: "1.2.3"}}},
		{"range-version", []PluginRequirement{{Name: "generic-json", Version: ">=1.2.3"}}},
		{"oversized-version", []PluginRequirement{{Name: "generic-json", Version: "1.2.3+" + strings.Repeat("a", 123)}}},
		{"requirement-count-overflow", slices.Repeat([]PluginRequirement{{Name: "generic-json"}}, 65)},
	} {
		t.Run(tc.name, func(t *testing.T) {
			copy := *model
			copy.Plugins = tc.requirements
			for _, encoding := range []Format{JSON, YAML} {
				var body bytes.Buffer
				if err := EmitEditable(&body, &copy, encoding); !errors.Is(err, ErrCapture) || body.Len() != 0 {
					t.Fatal("invalid plugin requirements reached editable emission", err)
				}
			}
		})
	}
}

// full_only: false
func TestPluginRequirementsRejectMalformedSources(t *testing.T) {
	for _, encoding := range []Format{JSON, YAML} {
		for _, tc := range []struct{ name, requirements string }{
			{"null-map", `null`},
			{"array-map", `[]`},
			{"unsafe-name", `{"../unknown":{}}`},
			{"non-ascii-name", `{"generic-jso雪":{}}`},
			{"oversized-name", `{"` + strings.Repeat("a", 256) + `":{}}`},
			{"duplicate-name", `{"generic-json":{},"generic-json":{}}`},
			{"duplicate-decoded-name", `{"generic-json":{},"generic-\u006ason":{}}`},
			{"null-requirement", `{"generic-json":null}`},
			{"scalar-requirement", `{"generic-json":"1.2.3"}`},
			{"unknown-field", `{"generic-json":{"setting":"local"}}`},
			{"path-field", `{"generic-json":{"path":"/tmp/plugin"}}`},
			{"url-field", `{"generic-json":{"url":"https://example.invalid/plugin"}}`},
			{"key-field", `{"generic-json":{"key":"untrusted"}}`},
			{"duplicate-version", `{"generic-json":{"version":"1.2.3","version":"1.2.3"}}`},
			{"empty-version", `{"generic-json":{"version":""}}`},
			{"null-version", `{"generic-json":{"version":null}}`},
			{"numeric-version", `{"generic-json":{"version":123}}`},
			{"range-version", `{"generic-json":{"version":">=1.2.3"}}`},
			{"wildcard-version", `{"generic-json":{"version":"1.2.*"}}`},
			{"leading-zero-version", `{"generic-json":{"version":"01.2.3"}}`},
			{"non-ascii-version", `{"generic-json":{"version":"1.2.3+雪"}}`},
			{"oversized-version", `{"generic-json":{"version":"1.2.3+` + strings.Repeat("a", 123) + `"}}`},
		} {
			t.Run(map[Format]string{JSON: "json", YAML: "yaml"}[encoding]+"/"+tc.name, func(t *testing.T) {
				setup := sourceSetupJSON
				if encoding == YAML {
					setup = sourceSetupYAML
				}
				path := filepath.Join(t.TempDir(), "configuration")
				if err := os.WriteFile(path, []byte(sourceWithPlugins(setup, encoding, tc.requirements)), 0600); err != nil {
					t.Fatal(err)
				}
				pair, err := Capture(t.Context(), path, encoding)
				if pair != nil {
					closeSourceOwner(t, pair)
				}
				if pair != nil || !errors.Is(err, ErrSourceInvalid) {
					t.Fatal("invalid source plugin requirement accepted", err)
				}
			})
		}
	}
}
