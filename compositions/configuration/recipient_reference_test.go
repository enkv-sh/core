func TestRecipientReferenceRenameTracksOnlySelectedMemberships(t *testing.T) {
	var entries strings.Builder
	entries.WriteByte('{')
	for i := range 512 {
		if i > 0 {
			entries.WriteByte(',')
		}
		entries.WriteString(strconv.Quote(strconv.Itoa(i)))
		entries.WriteString(`:{"confidentiality":"plain","recipients":["old","other"],"source":{"kind":"supplied","value":"x"}}`)
	}
	entries.WriteByte('}')
	declarations := `{"old":{"id":"` + preparedSourceRecipientID + `","display_name":"","encryption_key":"` + sourceEncryptionSelector + `"},"other":{"id":"` + strings.Repeat("07", 32) + `","display_name":"","encryption_key":"` + sourceEncryptionSelector + `"}}`
	editable := strings.Replace(preparationEditable(JSON, declarations), `"entries":{}`, `"entries":`+entries.String(), 1)
	other := strings.Replace(preparationRecipientRow(), strings.Repeat("06", 32), strings.Repeat("07", 32), 1)
	generated := strings.Replace(sourceGeneratedJSON, `"recipients":{}`, `"recipients":{"old":`+preparationRecipientRow()+`,"other":`+other+`}`, 1)
	pair := writePair(t, editable, generated, JSON)
	selected := "old"
	model, err := parseEditModel(t.Context(), pair, &Model{selectedReference: &selected})
	if err != nil {
		t.Fatal(err)
	}
	count := 0
	for _, span := range model.Spans {
		if span.Kind == SpanRecipientReference {
			count++
		}
	}
	if count != 512 || MaxSpans != 8192 || len(model.Spans) >= MaxSpans {
		t.Fatal("selected parser indexed unrelated memberships or changed span limit")
	}
	model = nil
	edit, err := PrepareRecipientReferenceEdit(t.Context(), pair, "old", "renamed")
	if err != nil {
		t.Fatal(err)
	}
	var declaration, satellite bytes.Buffer
	if err := edit.EmitEditable(t.Context(), &declaration, ".enkv/prod.generated.json"); err != nil {
		t.Fatal(err)
	}
	if err := edit.EmitGenerated(t.Context(), &satellite); err != nil {
		t.Fatal(err)
	}
	after, err := Parse(t.Context(), captureEditableEmission(t, declaration.Bytes(), satellite.Bytes(), JSON, ".enkv/prod.generated.json"))
	if err != nil || len(after.Entries) != 512 {
		t.Fatal("maximum selected membership candidate refused", err)
	}
	for _, entry := range after.Entries {
		if !reflect.DeepEqual(entry.Recipients, []string{"renamed", "other"}) {
			t.Fatal("selected rename changed unrelated membership or missed an entry")
		}
	}
}

