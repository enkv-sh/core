func TestRecipientReferenceRenameIncludesEmptyRoutingBlocks(t *testing.T) {
	for _, format := range []Format{JSON, YAML} {
		for _, empty := range []string{`{}`, `{"default":[],"entries":{}}`} {
			t.Run(fmt.Sprintf("%d/%s", format, empty), func(t *testing.T) {
				declaration := `{"old":{"id":"` + preparedSourceRecipientID + `","display_name":"old label","encryption_key":"` + sourceEncryptionSelector + `"}}`
				editable := preparationEditable(format, declaration)
				outputs := `{"destinations":{},"routing":` + empty + `}`
				if format == JSON {
					editable = strings.Replace(editable, `,"outputs":{"destinations":{},"routing":{}}`, "", 1)
					editable = `{"outputs":` + outputs + `,` + strings.TrimPrefix(editable, "{")
				} else {
					editable = "outputs: " + outputs + "\n" + strings.Replace(editable, "outputs:\n  destinations: {}\n  routing: {}\n", "", 1)
				}
				generated := strings.Replace(sourceGeneratedJSON, `"recipients":{}`, `"recipients":{"old":`+preparationRecipientRow()+`}`, 1)
				pair := writePair(t, editable, generated, format)
				before, err := Parse(t.Context(), pair)
				if err != nil {
					t.Fatal("empty-routing fixture refused or invented route", err)
				}
				edit, err := PrepareRecipientReferenceEdit(t.Context(), pair, "old", "new")
				if err != nil {
					t.Fatal(err)
				}
				var declarationBytes, satellite bytes.Buffer
				if err := edit.EmitEditable(t.Context(), &declarationBytes, before.Generated); err != nil {
					t.Fatal(err)
				}
				if err := edit.EmitGenerated(t.Context(), &satellite); err != nil {
					t.Fatal(err)
				}
				want := strings.ReplaceAll(string(maintenanceImageBytes(t, pair.Editable)), `"old":`, `"new":`)
				if format == YAML {
					want = strings.ReplaceAll(string(maintenanceImageBytes(t, pair.Editable)), `"old":`, "new:")
				}
				if declarationBytes.String() != want {
					t.Errorf("rename changed unrelated empty routing bytes: got %q want %q", declarationBytes.String(), want)
				}
				afterPair := captureEditableEmission(t, declarationBytes.Bytes(), satellite.Bytes(), format, before.Generated)
				after, err := Parse(t.Context(), afterPair)
				if err != nil || len(after.Recipients) != 1 || after.Recipients[0].Reference != "new" || !reflect.DeepEqual(before.Public, after.Public) || !reflect.DeepEqual(before.Routes, after.Routes) {
					t.Fatal("empty route rename changed whole-pair meaning", err)
				}
				back, err := PrepareRecipientReferenceEdit(t.Context(), afterPair, "new", "old")
				if err != nil {
					t.Fatal("empty route left stale collision key", err)
				}
				var restored bytes.Buffer
				if err := back.EmitEditable(t.Context(), &restored, before.Generated); err != nil {
					t.Fatal(err)
				}
				wantRestored := string(maintenanceImageBytes(t, pair.Editable))
				if format == YAML {
					wantRestored = strings.ReplaceAll(wantRestored, `"old":`, "old:")
				}
				if restored.String() != wantRestored {
					t.Fatal("reverse rename did not restore complete editable bytes")
				}
			})
		}
	}
}

