func TestRecipientReferenceRenamePreservesAllJoins(t *testing.T) {
	for _, format := range []Format{JSON, YAML} {
		t.Run(fmt.Sprint(format), func(t *testing.T) {
			editable := preparationEditable(format, `{"\u006fld":{"id":"`+preparedSourceRecipientID+`","encryption_key":"`+sourceEncryptionSelector+`","display_name":"Same label"}}`)
			editable = sourceWithPlugins(editable, format, sourcePluginRequirements)
			entry := `{"item":{"source":{"kind":"supplied","value":"old remains a value"},"recipients":["\u006fld"],"confidentiality":"plain"}}`
			outputs := `{"destinations":{"sink":{"plugin":"aws-secrets-manager","settings":{"account":"123456789012","region":"us-east-1"}}},"routing":{"default":["sink"],"entries":{"item":["sink"]}}}`
			if format == JSON {
				editable = strings.Replace(editable, `"entries":{}`, `"entries":`+entry, 1)
				editable = strings.Replace(editable, `"outputs":{"destinations":{},"routing":{}}`, `"outputs":`+outputs, 1)
			} else {
				editable = strings.Replace(editable, "entries: {}", "entries: "+entry+" # keep entries comment", 1)
				editable = strings.Replace(editable, "outputs:\n  destinations: {}\n  routing: {}", "outputs: "+outputs+" # keep outputs comment", 1)
			}
			secret := `"untouched" : { "sealed" : "` + base64.StdEncoding.EncodeToString(sourceEditEnvelope(t, "untouched")) + `" }`
			generated := strings.Replace(sourceGeneratedJSON, `"recipients":{}`, `"recipients":{"\u006fld":`+preparationRecipientRow()+`}`, 1)
			generated = strings.Replace(generated, `"secrets":{}`, `"secrets":{`+secret+`}`, 1)
			pair := writePair(t, editable, generated, format)
			before, err := Parse(t.Context(), pair)
			if err != nil {
				t.Fatal(err)
			}
			edit, err := PrepareRecipientReferenceEdit(t.Context(), pair, "old", "new雪")
			if err != nil {
				t.Fatal("reference rename refused complete source", err)
			}
			var nextEditable, nextGenerated bytes.Buffer
			if err := edit.EmitEditable(t.Context(), &nextEditable, before.Generated); err != nil {
				t.Fatal(err)
			}
			if err := edit.EmitGenerated(t.Context(), &nextGenerated); err != nil {
				t.Fatal(err)
			}
			requirePreservedPlugins(t, nextEditable.Bytes())
			after, err := Parse(t.Context(), captureEditableEmission(t, nextEditable.Bytes(), nextGenerated.Bytes(), format, before.Generated))
			if err != nil {
				t.Fatal("renamed actual candidate refused", err)
			}
			if after.Recipients[0].Reference != "new雪" || after.GeneratedRecipients[0].Reference != "new雪" || after.Entries[0].Recipients[0] != "new雪" || !reflect.DeepEqual(before.Routes, after.Routes) {
				t.Fatal("reference rename changed routing or missed a declaration/membership join")
			}
			if !reflect.DeepEqual(before.Public, after.Public) || !bytes.Contains(nextGenerated.Bytes(), []byte(secret)) || !strings.Contains(nextEditable.String(), "old remains a value") {
				t.Fatal("reference rename changed public identity, encrypted bytes or unrelated value")
			}
			if format == YAML && (!strings.Contains(nextEditable.String(), "# keep entries comment") || !strings.Contains(nextEditable.String(), "# keep outputs comment")) {
				t.Fatal("reference rename removed comments")
			}
		})
	}
}

