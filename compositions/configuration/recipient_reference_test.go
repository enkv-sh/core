func TestRecipientRoutingRejectsUnknownEmptyBlocks(t *testing.T) {
	for _, format := range []Format{JSON, YAML} {
		for _, empty := range []string{`{}`, `{"entries":{}}`} {
			t.Run(fmt.Sprintf("%d/%s", format, empty), func(t *testing.T) {
				editable := sourceSetupJSON
				outputs := `{"destinations":{},"routing":{"recipients":{"absent":` + empty + `}}}`
				if format == JSON {
					editable = strings.Replace(editable, `"outputs":{"destinations":{},"routing":{}}`, `"outputs":`+outputs, 1)
				} else {
					editable = strings.Replace(sourceSetupYAML, "outputs:\n  destinations: {}\n  routing: {}", "outputs: "+outputs, 1)
				}
				path := filepath.Join(t.TempDir(), "configuration")
				if err := os.WriteFile(path, []byte(editable), 0600); err != nil {
					t.Fatal(err)
				}
				pair, err := Capture(t.Context(), path, format)
				if pair != nil {
					defer closeSourceOwner(t, pair)
				}
				if err == nil {
					_, err = Parse(t.Context(), pair)
				}
				var diagnostic *Diagnostic
				if !errors.As(err, &diagnostic) || diagnostic.Field != "outputs.routing.recipients" || diagnostic.Reason != "unknown-field" || !errors.Is(err, ErrSourceInvalid) {
					t.Fatal("unknown empty routing key lost exact reference refusal", err)
				}
			})
		}
	}
}
