func TestRecipientReferenceRenameRefusesInvalidSelection(t *testing.T) {
	for _, condition := range []string{"missing-old", "occupied-new", "inactive-generated-new", "incomplete-old", "same-reference", "empty-new"} {
		t.Run(condition, func(t *testing.T) {
			declarations := `{"old":{"id":"` + preparedSourceRecipientID + `","display_name":"","encryption_key":"` + sourceEncryptionSelector + `"}}`
			if condition == "occupied-new" {
				declarations = strings.TrimSuffix(declarations, "}") + `,"new":{"id":"` + strings.Repeat("07", 32) + `","display_name":"","encryption_key":"` + sourceEncryptionSelector + `"}}`
			}
			generated := strings.Replace(sourceGeneratedJSON, `"recipients":{}`, `"recipients":{"old":`+preparationRecipientRow()+`}`, 1)
			if condition == "occupied-new" || condition == "inactive-generated-new" {
				other := strings.Replace(preparationRecipientRow(), strings.Repeat("06", 32), strings.Repeat("07", 32), 1)
				generated = strings.Replace(generated, `"recipients":{`, `"recipients":{"new":`+other+`,`, 1)
			}
			if condition == "incomplete-old" {
				generated = sourceGeneratedJSON
			}
			pair := writePair(t, preparationEditable(JSON, declarations), generated, JSON)
			oldReference, newReference := "old", "new"
			switch condition {
			case "missing-old":
				oldReference = "absent"
			case "same-reference":
				newReference = "old"
			case "empty-new":
				newReference = ""
			}
			if _, err := PrepareRecipientReferenceEdit(t.Context(), pair, oldReference, newReference); err == nil {
				t.Fatal("invalid reference selection admitted")
			}
		})
	}
}

