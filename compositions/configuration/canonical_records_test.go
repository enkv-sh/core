func sourceCanonicalRecordsJSON(t *testing.T, generators, outputs map[string][]byte) string {
	t.Helper()
	if generators == nil {
		generators = map[string][]byte{}
	}
	if outputs == nil {
		outputs = map[string][]byte{}
	}
	body, err := json.Marshal(struct {
		Generators map[string][]byte `json:"generators"`
		Outputs    map[string][]byte `json:"outputs"`
	}{Generators: generators, Outputs: outputs})
	if err != nil {
		t.Fatal(err)
	}
	return string(body)
}

func sourceGeneratedCanonical(t *testing.T, generators, outputs map[string][]byte) string {
	t.Helper()
	return strings.TrimSuffix(sourceGeneratedJSON, "}") + `,"canonical_records":` + sourceCanonicalRecordsJSON(t, generators, outputs) + `}`
}

// full_only: false
func TestUnusedCanonicalBackingDoesNotRestoreEditedDeclarations(t *testing.T) {
	for _, format := range []Format{JSON, YAML} {
		for _, change := range []string{"removed", "supplied", "author-settings"} {
			t.Run(fmt.Sprintf("%s/%s", map[Format]string{JSON: "json", YAML: "yaml"}[format], change), func(t *testing.T) {
				model, err := Parse(t.Context(), writePair(t, sourceSetupJSON, sourceGeneratedJSON, JSON))
				if err != nil {
					t.Fatal(err)
				}
				intent := sourceCanonicalIntent(t, false)
				model.Entries = []Entry{{Name: "token", Secret: true, Generated: &Generator{Intent: intent, Epoch: 7}}}
				model.Outputs = []OutputBinding{{DestinationID: "private", Binding: contract.NormalOutputBinding{DestinationID: "private", Destination: contract.OutputDestination{ConfigContractID: "private-config", ServiceContractID: "private-service", CanonicalSettings: []byte(`{"old":true}`)}, Targets: []contract.NormalOutputTarget{}}}}
				var generated bytes.Buffer
				if err := EmitGenerated(&generated, model); err != nil {
					t.Fatal(err)
				}
				switch change {
				case "removed":
					model.Entries, model.Outputs = nil, nil
				case "supplied":
					model.Entries = []Entry{{Name: "token", Plain: []byte("replacement")}}
					model.Outputs = nil
				case "author-settings":
					model.Entries[0].Generated = &Generator{Plugin: "private-generator", Settings: []byte(`{"new":true}`), Epoch: 8}
					model.Outputs[0].Plugin = "private-output"
					model.Outputs[0].Settings = []byte(`{"new":true}`)
				}
				var editable bytes.Buffer
				if err := EmitEditable(&editable, model, format); err != nil {
					t.Fatal(err)
				}
				pair := captureEditableEmission(t, editable.Bytes(), generated.Bytes(), format, model.Generated)
				for _, preparation := range []bool{false, true} {
					parse := Parse
					if preparation {
						parse = ParseForPreparation
					}
					got, err := parse(t.Context(), pair)
					if err != nil {
						t.Fatalf("editable-only %s refused (preparation=%t): %v", change, preparation, err)
					}
					if len(got.Entries) != len(model.Entries) || len(got.Outputs) != len(model.Outputs) || len(got.Public.Entries.Value) != len(model.Entries) || len(got.Public.OutputBindings.Value) != len(model.Outputs) {
						t.Fatal("unused backing restored a removed declaration")
					}
					if change == "supplied" && (got.Entries[0].Generated != nil || string(got.Entries[0].Plain) != "replacement") {
						t.Fatal("unused generator backing replaced supplied input")
					}
					if change == "author-settings" {
						g, o := got.Entries[0].Generated, got.Outputs[0]
						if string(g.Settings) != `{"new":true}` || len(g.Intent) != 0 || len(g.canonicalRecord) != 0 || string(o.Settings) != `{"new":true}` || len(o.canonicalRecord) != 0 || o.Binding.Destination.ConfigContractID != "" {
							t.Fatal("unused backing overrode the explicit author-input arm")
						}
					}
					var emitted bytes.Buffer
					if err := EmitGenerated(&emitted, got); err != nil {
						t.Fatal(err)
					}
					if bytes.Contains(emitted.Bytes(), []byte(`"canonical_records"`)) {
						t.Fatal("fresh generated image retained unused backing")
					}
				}
				if change != "removed" {
					selected, err := ParseForSet(t.Context(), pair, "token")
					if err != nil {
						t.Fatal(err)
					}
					edit, err := PrepareSuppliedEdit(pair, selected, "token", false, contract.InputEncodingRaw)
					if err != nil {
						t.Fatal(err)
					}
					var nextEditable, nextGenerated bytes.Buffer
					if err := edit.EmitEditable(t.Context(), &nextEditable, model.Generated, []byte("set value")); err != nil {
						t.Fatal(err)
					}
					if err := edit.EmitGenerated(t.Context(), &nextGenerated, nil); err != nil {
						t.Fatal(err)
					}
					if bytes.Contains(nextGenerated.Bytes(), []byte(`"token":`)) || !bytes.Contains(nextGenerated.Bytes(), []byte(`"private":`)) {
						t.Fatal("set did not remove only the selected unused backing")
					}
					next, err := Parse(t.Context(), captureEditableEmission(t, nextEditable.Bytes(), nextGenerated.Bytes(), format, model.Generated))
					if err != nil || len(next.Entries) != 1 || string(next.Entries[0].Plain) != "set value" {
						t.Fatal("set result did not preserve the requested plain replacement", err)
					}
				}
				if err := pair.CheckUnchanged(t.Context()); err != nil {
					t.Fatal("read-only admission changed the pair", err)
				}
			})
		}
	}
}

// full_only: false
func TestUnusedCanonicalBackingStillRequiresCompleteValidRecords(t *testing.T) {
	intent := sourceCanonicalIntent(t, false)
	binding, err := hex.DecodeString(canonicalOutputLiteral)
	if err != nil {
		t.Fatal(err)
	}
	for _, tc := range []struct {
		name, reason string
		generators   map[string][]byte
		outputs      map[string][]byte
	}{
		{"valid", "", map[string][]byte{"token": intent}, map[string][]byte{"private": binding}},
		{"malformed-generator", "invalid-canonical-intent", map[string][]byte{"token": {0}}, nil},
		{"malformed-output", "invalid-canonical-binding", nil, map[string][]byte{"private": {0}}},
		{"wrong-output-key", "invalid-canonical-binding", nil, map[string][]byte{"other": binding}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			_, err := Parse(t.Context(), writePair(t, sourceSetupJSON, sourceGeneratedCanonical(t, tc.generators, tc.outputs), JSON))
			if tc.reason == "" {
				if err != nil {
					t.Fatal("valid unused records refused", err)
				}
				return
			}
			var diagnostic *Diagnostic
			if !errors.As(err, &diagnostic) || diagnostic.Reason != tc.reason {
				t.Fatal("unused invalid record lost its refusal", err)
			}
		})
	}
	for _, excess := range []bool{false, true} {
		t.Run(fmt.Sprintf("target-limit/excess-%t", excess), func(t *testing.T) {
			output, err := contract.InspectNormalOutputBinding(binding)
			if err != nil {
				t.Fatal(err)
			}
			backing := map[string][]byte{}
			count := contract.MaxOutputTargets
			if excess {
				count++
			}
			for offset := 0; offset < count; offset += 256 {
				row := output
				row.DestinationID = fmt.Sprintf("output-%04d", offset)
				row.Targets = nil
				for i := 0; i < 256 && offset+i < count; i++ {
					target := output.Targets[0]
					target.Name = fmt.Sprintf("entry-%04d", offset+i)
					target.Target.CanonicalTarget = target.Name
					row.Targets = append(row.Targets, target)
				}
				backing[row.DestinationID], err = contract.EncodeNormalOutputBinding(row)
				if err != nil {
					t.Fatal(err)
				}
			}
			_, err = Parse(t.Context(), writePair(t, sourceSetupJSON, sourceGeneratedCanonical(t, nil, backing), JSON))
			if !excess && err != nil {
				t.Fatal("maximum unused target set refused", err)
			}
			var diagnostic *Diagnostic
			if excess && (!errors.As(err, &diagnostic) || diagnostic.Reason != "output-target-limit") {
				t.Fatal("unused targets bypassed the aggregate bound", err)
			}
		})
	}
}
